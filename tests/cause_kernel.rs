#![cfg_attr(test, allow(clippy::unwrap_used, clippy::expect_used))]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::AtomicUsize;

use serde_json::Value;

mod support;

const BY_VALUE: &str = "clippy::large_types_passed_by_value";
const BUILD_STEP: &str = "rust_doctor::repo::secret_in_build_step";

static NEXT_WORKSPACE: AtomicUsize = AtomicUsize::new(0);

const BY_VALUE_SOURCE: &str = "#[derive(Clone, Copy)]\n\
pub struct Big([u64; 64]);\n\
\n\
#[derive(Clone, Copy)]\n\
pub struct Huge([u64; 80]);\n\
\n\
fn first(value: Big) -> u64 {\n    value.0[0]\n}\n\
\n\
fn second(value: crate::Big) -> u64 {\n    value.0[1]\n}\n\
\n\
fn third(value: Big) -> u64 {\n    value.0[2]\n}\n\
\n\
fn fourth(value: Huge) -> u64 {\n    value.0[3]\n}\n\
\n\
pub fn total() -> u64 {\n    let big = Big([1; 64]);\n    first(big) + second(big) + third(big) + fourth(Huge([2; 80]))\n}\n";

fn workspace(scope: &str, source: &str) -> PathBuf {
    let root = support::temporary_target(scope, &NEXT_WORKSPACE);
    if root.exists() {
        fs::remove_dir_all(&root).unwrap();
    }
    fs::create_dir_all(root.join("src")).unwrap();
    fs::write(
        root.join("Cargo.toml"),
        "[package]\nname = \"cause-fixture\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
    )
    .unwrap();
    fs::write(
        root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\n\
         version = 4\n\n\
         [[package]]\n\
         name = \"cause-fixture\"\n\
         version = \"0.1.0\"\n",
    )
    .unwrap();
    fs::write(root.join(".gitignore"), "/target\n").unwrap();
    fs::write(root.join("src/lib.rs"), source).unwrap();
    root
}

fn workflow(variable: &str) -> String {
    format!(
        "name: release\non: push\njobs:\n  build:\n    runs-on: ubuntu-latest\n    steps:\n      - uses: actions/checkout@v4\n      - name: Build\n        env:\n          {variable}: ${{{{ secrets.ANALYTICS }}}}\n        run: cargo build --release\n"
    )
}

fn with_workflows(root: &Path, variables: &[&str]) {
    fs::create_dir_all(root.join(".github/workflows")).unwrap();
    for (index, variable) in variables.iter().enumerate() {
        fs::write(
            root.join(format!(".github/workflows/release-{index}.yml")),
            workflow(variable),
        )
        .unwrap();
    }
    commit_all(root);
}

fn git(root: &Path, arguments: &[&str]) {
    let output = Command::new("git")
        .args(arguments)
        .current_dir(root)
        .output()
        .expect("git should start");
    assert!(output.status.success(), "git {arguments:?}: {}", String::from_utf8_lossy(&output.stderr));
}

fn commit_all(root: &Path) {
    git(root, &["init", "--quiet"]);
    git(root, &["config", "user.name", "Rust Doctor"]);
    git(root, &["config", "user.email", "rust-doctor@example.invalid"]);
    git(root, &["add", "-A"]);
    git(root, &["commit", "--quiet", "-m", "base"]);
}

fn run(root: &Path, json: bool) -> Vec<u8> {
    let mut arguments: Vec<String> = vec![
        root.to_str().unwrap().to_owned(),
        "--yes".to_owned(),
        "--verbose".to_owned(),
    ];
    if json {
        arguments.push("--json".to_owned());
    }
    arguments.extend(support::NO_ADVISORY_DB.iter().map(|value| (*value).to_owned()));
    let output = support::rust_doctor()
        .args(&arguments)
        .env("CARGO_TARGET_DIR", support::scan_target(root))
        .env("NO_COLOR", "1")
        .output()
        .unwrap();
    assert!(!output.stdout.is_empty(), "{}", String::from_utf8_lossy(&output.stderr));
    output.stdout
}

fn scan(root: &Path) -> Value {
    serde_json::from_slice(&run(root, true)).unwrap()
}

fn linear(root: &Path) -> String {
    let printed = String::from_utf8_lossy(&run(root, false)).into_owned();
    printed.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn findings<'a>(report: &'a Value, rule: &str) -> Vec<&'a Value> {
    report["diagnostics"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|diagnostic| diagnostic["code"] == rule)
        .collect()
}

#[test]
fn by_value_findings_of_one_type_share_one_cause_and_keep_their_identity() {
    let root = workspace("cause/by-value", BY_VALUE_SOURCE);
    let report = scan(&root);
    assert_eq!(report["status"], "complete", "{:#}", report["errors"]);

    let observed = findings(&report, BY_VALUE);
    let mut causes: Vec<&str> = observed
        .iter()
        .map(|finding| finding["cause"].as_str().unwrap_or_default())
        .collect();
    causes.sort_unstable();
    assert_eq!(
        causes,
        ["Big (512 byte)", "Big (512 byte)", "Big (512 byte)", "Huge (640 byte)"],
        "{observed:#?}"
    );
    for finding in &observed {
        let message = finding["message"].as_str().unwrap();
        assert!(!message.contains("Big") && !message.contains("Huge"), "{message}");
    }

    let printed = linear(&root);
    assert!(
        printed.contains("4 findings, 2 causes: Big (512 byte) x3, ..."),
        "{printed}"
    );
}

#[test]
fn a_cause_never_changes_the_identity_of_a_finding() {
    let root = workspace("cause/identity", BY_VALUE_SOURCE);
    let report = scan(&root);
    let mut renamed = BY_VALUE_SOURCE.replace("Big", "Fat");
    renamed = renamed.replace("Huge", "Vast");
    let other = workspace("cause/identity-renamed", &renamed);
    let renamed_report = scan(&other);
    let identity = |report: &Value| {
        let mut ids: Vec<(String, String, String)> = findings(report, BY_VALUE)
            .iter()
            .map(|finding| {
                (
                    finding["id"].as_str().unwrap().to_owned(),
                    finding["message"].as_str().unwrap().to_owned(),
                    finding["span"].to_string(),
                )
            })
            .collect();
        ids.sort();
        ids
    };
    let before = identity(&report);
    let after = identity(&renamed_report);
    assert_eq!(before.len(), 4);
    assert_eq!(
        before, after,
        "renaming the type changes every cause and must change no id, message or span"
    );
    let causes = |report: &Value| -> Vec<String> {
        findings(report, BY_VALUE)
            .iter()
            .map(|finding| finding["cause"].as_str().unwrap_or_default().to_owned())
            .collect()
    };
    assert_ne!(causes(&report), causes(&renamed_report));
}

#[test]
fn one_variable_in_three_workflows_is_one_cause() {
    let root = workspace("cause/one-variable", "pub fn fixture() -> u32 {\n    2\n}\n");
    with_workflows(&root, &["ANALYTICS_KEY", "ANALYTICS_KEY", "ANALYTICS_KEY"]);
    let report = scan(&root);
    assert_eq!(report["status"], "complete", "{:#}", report["errors"]);
    let observed = findings(&report, BUILD_STEP);
    assert_eq!(observed.len(), 3, "{report:#}");
    for finding in &observed {
        assert_eq!(finding["cause"], "ANALYTICS_KEY", "{finding:#}");
    }
    let printed = linear(&root);
    assert!(
        printed.contains("3 findings, 1 cause: ANALYTICS_KEY x3"),
        "{printed}"
    );

    let single = workspace("cause/one-workflow", "pub fn fixture() -> u32 {\n    2\n}\n");
    with_workflows(&single, &["ANALYTICS_KEY"]);
    let alone = scan(&single);
    assert_eq!(findings(&alone, BUILD_STEP).len(), 1, "{alone:#}");
    assert_eq!(
        report["audit"]["score"]["dimensions"]["security"],
        alone["audit"]["score"]["dimensions"]["security"],
        "the same variable in three workflows weighs what one finding weighs"
    );
    assert_eq!(report["audit"]["score"]["value"], alone["audit"]["score"]["value"]);
}
