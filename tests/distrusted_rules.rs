#![cfg_attr(test, allow(clippy::unwrap_used, clippy::expect_used))]

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::AtomicUsize;

use serde_json::Value;

mod support;

const COMPLEX: &str = "rust_doctor::structure::complex_function";

static NEXT_WORKSPACE: AtomicUsize = AtomicUsize::new(0);

fn tangled() -> String {
    let mut source = String::from("pub fn tangled(values: &[i64]) -> i64 {\n    let mut total = 0;\n    for value in values {\n");
    for step in 0..30 {
        let _ = writeln!(
            source,
            "        if *value > {step} && *value % {} == 0 {{\n            total += {step};\n        }}",
            step + 2
        );
    }
    source.push_str("    }\n    total\n}\n");
    source
}

fn flat() -> String {
    let mut source = String::from("pub fn flat(value: u32) -> u32 {\n    match value {\n");
    for arm in 0..35 {
        let _ = writeln!(source, "        {arm} => {},", arm + 10);
    }
    source.push_str("        _ => 0,\n    }\n}\n");
    source
}

fn workspace(scope: &str, source: &str) -> PathBuf {
    let root = support::fresh_workspace(scope, &NEXT_WORKSPACE);
    fs::create_dir_all(root.join("src")).unwrap();
    fs::write(
        root.join("Cargo.toml"),
        "[package]\nname = \"distrusted-fixture\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
    )
    .unwrap();
    fs::write(
        root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n\
         # It is not intended for manual editing.\n\
         version = 4\n\n\
         [[package]]\n\
         name = \"distrusted-fixture\"\n\
         version = \"0.1.0\"\n",
    )
    .unwrap();
    fs::write(root.join("src/lib.rs"), source).unwrap();
    root
}

fn scan(root: &Path, extra: &[&str]) -> Value {
    let mut arguments: Vec<String> = vec![
        root.to_str().unwrap().to_owned(),
        "--yes".to_owned(),
        "--json".to_owned(),
    ];
    arguments.extend(support::NO_ADVISORY_DB.iter().map(|value| (*value).to_owned()));
    for entry in rust_doctor::catalog() {
        if entry.id.starts_with("clippy::") {
            arguments.push("--rule".to_owned());
            arguments.push(format!("{}=off", entry.id));
        }
    }
    arguments.extend(extra.iter().map(|value| (*value).to_owned()));
    let output = support::rust_doctor()
        .args(&arguments)
        .env("CARGO_TARGET_DIR", support::scan_target(root))
        .output()
        .unwrap();
    assert!(!output.stdout.is_empty(), "{}", String::from_utf8_lossy(&output.stderr));
    serde_json::from_slice(&output.stdout).unwrap()
}

fn complex_findings(report: &Value) -> Vec<&Value> {
    report["diagnostics"]
        .as_array()
        .unwrap()
        .iter()
        .filter(|diagnostic| diagnostic["code"] == COMPLEX)
        .collect()
}

#[test]
fn a_rule_the_corpus_distrusts_publishes_at_info_and_keeps_its_base_severity() {
    let root = workspace("distrusted/tangled", &tangled());
    let report = scan(&root, &[]);
    assert_eq!(report["status"], "complete", "{:#}", report["errors"]);
    let findings = complex_findings(&report);
    assert_eq!(findings.len(), 1, "{report:#}");
    let finding = findings[0];
    assert_eq!(finding["severity"], "info", "{finding:#}");
    assert_eq!(finding["base_severity"], "warning", "{finding:#}");
    let message = finding["message"].as_str().unwrap();
    assert!(
        message.contains("cyclomatic complexity") && message.contains("cognitive complexity"),
        "{message}"
    );
    assert_eq!(report["audit"]["score"]["dimensions"]["maintainability"], 100);
    assert_eq!(report["gate"]["status"], "passed", "{:#}", report["gate"]);
}

#[test]
fn a_level_the_request_sets_overrides_the_distrust() {
    let root = workspace("distrusted/requested", &tangled());
    let report = scan(&root, &["--rule", &format!("{COMPLEX}=warn")]);
    let findings = complex_findings(&report);
    assert_eq!(findings.len(), 1, "{report:#}");
    assert_eq!(findings[0]["severity"], "warning", "{:#}", findings[0]);
    assert!(report["audit"]["score"]["dimensions"]["maintainability"].as_u64().unwrap() < 100);
}

#[test]
fn a_flat_match_reaches_one_threshold_and_is_not_reported() {
    let root = workspace("distrusted/flat", &flat());
    let report = scan(&root, &["--rule", &format!("{COMPLEX}=warn")]);
    assert_eq!(report["status"], "complete", "{:#}", report["errors"]);
    assert!(complex_findings(&report).is_empty(), "{report:#}");
}
