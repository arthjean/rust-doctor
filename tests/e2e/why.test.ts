// WY-01 to WY-35 of `tasks/e2e-catalog/subcommands.md` section 3: `why`, live
// and from a saved report. Two committed workspaces are scanned once each:
// `twoMember`, and `mixed`, which holds an ignored, a generated, a suppressed
// and a manifest site. A row that needs its own history builds it.
import { beforeAll, describe, expect, test } from "bun:test";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { runDoctor, scratchDir, treeFingerprint, type DoctorOptions, type DoctorRun } from "./e2e-helpers";
import { twoMemberFiles } from "./explain-support";
import { gitScenario, type Repo } from "./git-scenario";

type Hit = { rule_id: string; severity: string; level_source: string; span: { line_start: number; column_start: number } };
type Answer = { location: { path: string; line: number; column: number | null }; hits: Hit[] };
type Report = { schema_version: number; diagnostics: Array<{ message: string; help: string }> };

const MIXED: Record<string, string> = {
  "Cargo.toml": '[package]\nname = "mixed"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n\n[lints.clippy]\ndbg_macro = "allow"\n\n[workspace]\n',
  "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "mixed"\nversion = "0.1.0"\n',
  ".gitignore": "/target\n",
  "rust-doctor.toml": '[ignore]\npaths = ["src/vendored"]\n',
  "src/lib.rs": "pub mod out;\npub mod shell;\npub mod vendored;\n",
  "src/out/mod.rs": "// @generated by build tooling. DO NOT EDIT.\npub fn generated() -> u8 {\n    todo!()\n}\n",
  "src/vendored/mod.rs": "pub fn vendored() -> u8 {\n    todo!()\n}\n",
  "src/shell.rs": [
    "use std::process::Command;",
    "pub fn applied(user: &str) {",
    "    // rust-doctor: allow(rust_doctor::source::dynamic_shell_command) -- the caller fixes argv",
    '    let _ = Command::new("sh").arg("-c").arg(format!("run {user}"));',
    "}",
    "pub fn no_reason(user: &str) {",
    "    // rust-doctor: allow(rust_doctor::source::dynamic_shell_command)",
    '    let _ = Command::new("sh").arg("-c").arg(format!("run {user}"));',
    "}",
    "",
  ].join("\n"),
};

type Scanned = { repo: Repo; target: string; report: string; json: Report };

let twoMember: Scanned;
let mixed: Scanned;

async function scanned(name: string, files: Record<string, string>, exitCode: number): Promise<Scanned> {
  const repo = await gitScenario(name).write(files).commit("base").build();
  const target = join(repo.sandbox.dir, "target");
  const scan = await runDoctor([repo.path, "--yes", "--json"], { sandbox: repo.sandbox, target });
  expect(scan.exitCode).toBe(exitCode);
  const report = join(repo.sandbox.dir, "report.json");
  writeFileSync(report, scan.stdout);
  return { repo, target, report, json: scan.json as Report };
}

beforeAll(async () => {
  [twoMember, mixed] = await Promise.all([
    scanned("why-two-member", twoMemberFiles(), 1),
    scanned("why-mixed", MIXED, 0),
  ]);
});

// `why` in the workspace, asserting it wrote nothing there.
async function why(on: Scanned, args: string[], options: DoctorOptions = {}): Promise<DoctorRun> {
  const before = treeFingerprint(on.repo.path);
  const run = await runDoctor(["why", ...args], { sandbox: on.repo.sandbox, cwd: on.repo.path, target: on.target, ...options });
  expect(treeFingerprint(on.repo.path)).toBe(before);
  return run;
}

function answered(run: DoctorRun, stdout: string): void {
  expect(run.exitCode).toBe(0);
  expect(run.stderr).toBe("");
  expect(run.stdout).toBe(stdout);
}

function refused(run: DoctorRun, stderr: string): void {
  expect(run.exitCode).toBe(2);
  expect(run.stdout).toBe("");
  expect(run.stderr).toBe(stderr);
}

function savedDoc(name: string, body: string): string {
  const path = join(scratchDir(name), name);
  writeFileSync(path, body);
  return path;
}

describe("why on a live scan", () => {
  test("WY-01 a reported line prints the finding, its frame and the directive that silences it", async () => {
    const run = await why(twoMember, ["a/src/lib.rs:2"]);
    expect(run.exitCode).toBe(0);
    expect(run.stderr).toBe("");
    const lines = run.stdout.split("\n");
    expect(lines.slice(0, 2)).toEqual(["clippy::todo (error)", "Level source: config-rule"]);
    expect(lines).toContain("Help: Replace todo! with the intended implementation or remove the reachable placeholder.");
    expect(lines).toContain("Rule: https://rust-doctor.com/rules/clippy%3A%3Atodo");
    expect(lines).toContain("a/src/lib.rs:2:5");
    expect(lines).toContain("> 2 |     todo!()");
    expect(lines).toContain("    |     ^^^^^^^");
    expect(lines).toContain('To suppress this site: #[expect(clippy::todo, reason = "<why this site is not a defect>")]');
  });

  test("WY-02 --json carries the location and each hit's documented keys", async () => {
    const run = await why(twoMember, ["a/src/lib.rs:2:5", "--json"]);
    expect(run.exitCode).toBe(0);
    const answer = run.json as Answer;
    expect(Object.keys(answer).sort()).toEqual(["hits", "location"]);
    expect(answer.location).toEqual({ path: "a/src/lib.rs", line: 2, column: 5 });
    expect(answer.hits).toHaveLength(1);
    expect(Object.keys(answer.hits[0]!).sort()).toEqual(
      ["directive", "help", "level_source", "message", "path", "rule_id", "severity", "span", "suppressions", "url"],
    );
    expect(Object.keys(answer.hits[0]!.span).sort()).toEqual(["column_end", "column_start", "line_end", "line_start"]);
  });

  test("WY-03 a leading ./ names the same file", async () => {
    const run = await why(twoMember, ["./a/src/lib.rs:2"]);
    expect(run.stdout).toBe((await why(twoMember, ["a/src/lib.rs:2"])).stdout);
  });

  test("WY-04 a path relative to a subdirectory resolves against it", async () => {
    const run = await why(twoMember, ["lib.rs:2"], { cwd: join(twoMember.repo.path, "a/src") });
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toBe((await why(twoMember, ["a/src/lib.rs:2"])).stdout);
  });

  test("WY-05 an absolute path names the same file", async () => {
    const run = await why(twoMember, [join(twoMember.repo.path, "a/src/lib.rs:2")]);
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toBe((await why(twoMember, ["a/src/lib.rs:2"])).stdout);
  });

  test("WY-06 a clean line says nothing is reported there", async () => {
    answered(await why(twoMember, ["a/src/lib.rs:6"]), "Nothing is reported at a/src/lib.rs:6.\n");
  });

  test("WY-07 a line past the end of the file is not bounds-checked", async () => {
    answered(await why(twoMember, ["a/src/lib.rs:999"]), "Nothing is reported at a/src/lib.rs:999.\n");
  });

  test("WY-08 an override that switches the rule off leaves nothing reported", async () => {
    answered(await why(twoMember, ["b/src/lib.rs:2"]), "Nothing is reported at b/src/lib.rs:2.\n");
  });
});

describe("why on a saved report", () => {
  test("WY-09 a saved report answers byte for byte as the live scan, with no program on PATH", async () => {
    const live = await why(twoMember, ["a/src/lib.rs:2"]);
    answered(await why(twoMember, ["a/src/lib.rs:2", "--report", twoMember.report], { env: { PATH: "" } }), live.stdout);
  });

  test("WY-10 --json from a saved report carries the same hit and no column", async () => {
    const live = (await why(twoMember, ["a/src/lib.rs:2", "--json"])).json as Answer;
    const run = await why(twoMember, ["a/src/lib.rs:2", "--report", twoMember.report, "--json"]);
    expect(run.exitCode).toBe(0);
    const answer = run.json as Answer;
    expect(answer.location).toEqual({ path: "a/src/lib.rs", line: 2, column: null });
    expect(answer.hits).toEqual(live.hits);
  });

  test("WY-11 a saved report matches the path as written from any directory", async () => {
    const run = await why(twoMember, ["a/src/lib.rs:2", "--report", twoMember.report], { cwd: "/" });
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toStartWith("clippy::todo (error)\nLevel source: config-rule\n");
  });

  // US-008 fixed subcommands/F6: `why --report` checks the schema as `report
  // markdown` does.
  test("WY-12 a document without schema_version is refused as report markdown refuses it", async () => {
    const path = savedDoc("notareport.json", '{"a":1}');
    const message = `rust-doctor: ${path}: the report carries no schema_version, and this binary reads ${twoMember.json.schema_version}.\n`;
    refused(await why(twoMember, ["a/src/lib.rs:2", "--report", path]), message);
    expect((await runDoctor(["report", "markdown", path], { sandbox: twoMember.repo.sandbox })).stderr).toBe(message);
  });

  test("WY-13 a newer schema is refused as report markdown refuses it", async () => {
    const report = JSON.parse(readFileSync(twoMember.report, "utf8")) as Report;
    const next = report.schema_version + 1;
    const path = savedDoc("future.json", JSON.stringify({ ...report, schema_version: next }));
    const message = `rust-doctor: ${path}: the report has schema_version ${next}, and this binary reads ${report.schema_version}: render it with the rust-doctor that wrote it.\n`;
    refused(await why(twoMember, ["a/src/lib.rs:2", "--report", path]), message);
    expect((await runDoctor(["report", "markdown", path], { sandbox: twoMember.repo.sandbox })).stderr).toBe(message);
  });

  test("WY-14 a missing report is refused naming it", async () => {
    refused(await why(twoMember, ["x:2", "--report", "/nonexistent.json"]), "rust-doctor: /nonexistent.json: the report could not be read (entity not found).\n");
  });

  test("WY-15 an empty report is not valid JSON", async () => {
    const path = savedDoc("empty.json", "");
    refused(await why(twoMember, ["x:2", "--report", path]), `rust-doctor: ${path}: the report is not valid JSON (line 1, column 0).\n`);
  });
});

describe("why arguments", () => {
  test("WY-16 a location without a positive line is refused naming it", async () => {
    for (const location of ["a/src/lib.rs:0", "a/src/lib.rs:-1", "a/src/lib.rs", "a/src/lib.rs:2:0", "a/src/lib.rs:x", "a/src/lib.rs:2:x", ":2"]) {
      const run = await why(twoMember, [location]);
      expect({ location, exitCode: run.exitCode, stdout: run.stdout, stderr: run.stderr }).toEqual({
        location,
        exitCode: 2,
        stdout: "",
        stderr: `rust-doctor: why ${location}: expected PATH:LINE[:COLUMN] with a positive LINE.\n`,
      });
    }
  });

  test("WY-17 only the last two colon fields are the line and the column", async () => {
    answered(await why(twoMember, ["a/src/lib.rs:2:3:4", "--report", twoMember.report]), "Nothing is reported at a/src/lib.rs:2:3.\n");
  });

  test("WY-18 a colon inside the path stays in the path", async () => {
    answered(await why(twoMember, ["a/src/we:ird.rs:3", "--report", twoMember.report]), "Nothing is reported at a/src/we:ird.rs:3.\n");
  });

  test("WY-19 a file that does not exist is refused live", async () => {
    refused(await why(twoMember, ["a/src/nope.rs:1"]), "rust-doctor: why a/src/nope.rs: the file cannot be read.\n");
  });

  test("WY-20 a file outside every package is refused live", async () => {
    const dir = scratchDir("wy-20");
    writeFileSync(join(dir, "notareport.json"), "{}\n");
    const before = treeFingerprint(dir);
    const run = await runDoctor(["why", "notareport.json:1"], { sandbox: twoMember.repo.sandbox, cwd: dir });
    expect(treeFingerprint(dir)).toBe(before);
    refused(run, "rust-doctor: why notareport.json: no Cargo package holds this file.\n");
  });

  test("WY-21 the virtual root manifest belongs to no package, so it is refused live", async () => {
    refused(await why(twoMember, ["Cargo.toml:1"]), "rust-doctor: why Cargo.toml: no Cargo package holds this file.\n");
  });

  test("WY-22 a member manifest scans that member", async () => {
    answered(await why(twoMember, ["a/Cargo.toml:1"]), "Nothing is reported at a/Cargo.toml:1.\n");
  });

  test("WY-23 a scan that fails names its cause", async () => {
    const repo = await gitScenario("wy-23")
      .write({
        "Cargo.toml": '[package]\nname = "wy23"\nversion = "0.1.0"\nedition = "2024"\n\n[workspace]\n',
        "src/lib.rs": "pub fn a() -> u8 {\n    1\n}\n// four\n",
        "rust-doctor.toml": "nope = 1\n",
      })
      .commit("base")
      .build();
    const before = treeFingerprint(repo.path);
    const run = await runDoctor(["why", "src/lib.rs:4"], { sandbox: repo.sandbox, cwd: repo.path });
    expect(treeFingerprint(repo.path)).toBe(before);
    refused(run, "rust-doctor: why src/lib.rs: the scan failed: Invalid rust-doctor.toml at line 1, column 1.\n");
  });
});

describe("why on excluded and suppressed sites", () => {
  test("WY-24 an ignored path says so, live and from the report", async () => {
    const expected = "src/vendored/mod.rs is ignored by rust-doctor.toml: nothing there is reported.\n";
    answered(await why(mixed, ["src/vendored/mod.rs:2"]), expected);
    answered(await why(mixed, ["src/vendored/mod.rs:2", "--report", mixed.report]), expected);
  });

  test("WY-25 a file with a generated header says so, live and from the report", async () => {
    const expected = "src/out/mod.rs is declared generated or vendored: nothing there is graded.\n";
    answered(await why(mixed, ["src/out/mod.rs:3"]), expected);
    answered(await why(mixed, ["src/out/mod.rs:3", "--report", mixed.report]), expected);
  });

  test("WY-26 a committed linguist-generated attribute is honored live", async () => {
    const repo = await gitScenario("wy-26")
      .fixture("projects/clean")
      .write({
        ".gitignore": "/target\n",
        ".gitattributes": "src/out/** linguist-generated\n",
        "src/out/mod.rs": "pub fn generated() -> u8 {\n    todo!()\n}\n",
      })
      .append("src/lib.rs", "pub mod out;\n")
      .commit("base")
      .build();
    const before = treeFingerprint(repo.path);
    const run = await runDoctor(["why", "src/out/mod.rs:2"], { sandbox: repo.sandbox, cwd: repo.path });
    expect(treeFingerprint(repo.path)).toBe(before);
    answered(run, "src/out/mod.rs is declared generated or vendored: nothing there is graded.\n");
  });

  test.failing("WY-27 subcommands/F13 a saved report answers as the live scan does on a declared-generated file", async () => {
    const repo = await gitScenario("wy-27")
      .fixture("projects/clean")
      .write({
        ".gitignore": "/target\n",
        ".gitattributes": "src/out/** linguist-generated\n",
        "src/out/mod.rs": "pub fn generated() -> u8 {\n    todo!()\n}\n",
      })
      .append("src/lib.rs", "pub mod out;\n")
      .commit("base")
      .build();
    const report = join(repo.sandbox.dir, "report.json");
    writeFileSync(report, (await runDoctor([repo.path, "--yes", "--json"], { sandbox: repo.sandbox })).stdout);
    const live = await runDoctor(["why", "src/out/mod.rs:2"], { sandbox: repo.sandbox, cwd: repo.path });
    const saved = await runDoctor(["why", "src/out/mod.rs:2", "--report", report], { sandbox: repo.sandbox, cwd: repo.path });
    expect(live.stdout).toContain("declared generated or vendored");
    expect(saved.stdout).toBe(live.stdout);
  });

  test("WY-28 an attribute on an untracked file does not exclude it: the file is graded", async () => {
    const repo = await gitScenario("wy-28")
      .fixture("projects/clean")
      .write({ ".gitignore": "/target\n", ".gitattributes": "src/out/** linguist-generated\n" })
      .commit("base")
      .untracked({ "src/out/mod.rs": "pub fn generated() -> u8 {\n    todo!()\n}\n" })
      .append("src/lib.rs", "pub mod out;\n")
      .build();
    const before = treeFingerprint(repo.path);
    const run = await runDoctor(["why", "src/out/mod.rs:2"], { sandbox: repo.sandbox, cwd: repo.path });
    expect(treeFingerprint(repo.path)).toBe(before);
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toStartWith("clippy::todo (");
    expect(run.stdout).toContain("> 2 |     todo!()\n");
  });

  test.failing("WY-29 subcommands/F14 a line an #[expect] silences names the attribute", async () => {
    const repo = await gitScenario("wy-29")
      .fixture("projects/clean")
      .write({ ".gitignore": "/target\n" })
      .append("src/lib.rs", '\n#[expect(clippy::todo, reason = "staged rollout")]\npub fn later() -> u8 {\n    todo!()\n}\n')
      .commit("base")
      .build();
    const run = await runDoctor(["why", "src/lib.rs:9"], { sandbox: repo.sandbox, cwd: repo.path });
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toContain("expect");
  });

  test.failing("WY-30 subcommands/F14 a line an applied directive silences names the directive", async () => {
    const run = await why(mixed, ["src/shell.rs:4", "--report", mixed.report]);
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toContain("src/shell.rs:3");
    expect(run.stdout).toContain("rust_doctor::source::dynamic_shell_command");
  });

  test("WY-31 a directive without a reason is listed under the hit it fails to silence", async () => {
    const run = await why(mixed, ["src/shell.rs:8", "--report", mixed.report]);
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toStartWith("rust_doctor::source::dynamic_shell_command (warning)\n");
    expect(run.stdout).toContain("Suppression at src/shell.rs:7: rust_doctor::source::dynamic_shell_command (missing-reason)\n");
    expect(run.stdout).not.toContain("To suppress");
  });

  test("WY-32 escape sequences in a saved message are stripped and its lines kept", async () => {
    const report = JSON.parse(readFileSync(twoMember.report, "utf8")) as Report;
    report.diagnostics[0]!.message = "first\x1b[31mred\x1b[0m\nsecond line";
    report.diagnostics[0]!.help = "help\x1b]0;title\x07 text";
    const path = savedDoc("escapes.json", JSON.stringify(report));
    const run = await why(twoMember, ["a/src/lib.rs:2", "--report", path]);
    expect(run.exitCode).toBe(0);
    expect(run.stdout).not.toContain("\x1b");
    expect(run.stdout).not.toContain("\x07");
    expect(run.stdout).toContain("\nfirstred\nsecond line\nHelp: help text\n");
  });

  test("WY-33 a manifest finding suggests the TOML comment directive", async () => {
    const run = await why(mixed, ["Cargo.toml:8", "--report", mixed.report]);
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toStartWith("rust_doctor::cargo::permissive_lint_table (warning)\n");
    expect(run.stdout).toContain(
      "To suppress this site: # rust-doctor: allow(rust_doctor::cargo::permissive_lint_table) -- <why this site is not a defect>\n",
    );
  });
});

