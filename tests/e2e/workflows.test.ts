describe("Stop hook", () => {
  test("WF-12 the installed command refuses the turn, then passes once fixed, then honors the loop guard", async () => {
    const repo = await clean("wf-12");
    expect((await runDoctor(["hook", "install", "claude", repo.path], { sandbox: repo.sandbox })).exitCode).toBe(0);
    const settings = JSON.parse(readFileSync(join(repo.path, ".claude/settings.local.json"), "utf8")) as {
      hooks: { Stop: Array<{ hooks: Array<{ command: string }> }> };
    };
    const command = settings.hooks.Stop[0]!.hooks[0]!.command;
    expect(command).toBe("rust-doctor hook run claude");
    const payload = (active: boolean) =>
      JSON.stringify({
        session_id: "e2e-session",
        transcript_path: join(repo.sandbox.home, "t.jsonl"),
        cwd: repo.path,
        permission_mode: "default",
        hook_event_name: "Stop",
        stop_hook_active: active,
      });
    // The hook judges the turn and writes nothing into the repository.
    const stop = async (active: boolean) => {
      const fingerprint = treeFingerprint(repo.path);
      const run = await runCommand(["sh", "-c", command], {
        sandbox: repo.sandbox,
        cwd: repo.path,
        stdin: payload(active),
        env: { CLAUDE_PROJECT_DIR: repo.path, CARGO_TARGET_DIR: join(repo.sandbox.dir, "stop-target") },
      });
      expect(treeFingerprint(repo.path)).toBe(fingerprint);
      return run;
    };
    writeFileSync(join(repo.path, "src/lib.rs"), `${CLEAN["src/lib.rs"]}\n${TODO_LINE}`);
    const refused = await stop(false);
    expect(refused.exitCode).toBe(2);
    expect(refused.stdout).toBe("");
    expect(refused.stderr).toBe(
      "rust-doctor found 1 finding in the lines this turn changed:\n" +
        "- clippy::todo src/lib.rs:6 `todo` should not be present in production code\n" +
        "Fix them, then rescan: rust-doctor . --scope lines --base HEAD --include-untracked --blocking warning\n",
    );
    writeFileSync(join(repo.path, "src/lib.rs"), `${CLEAN["src/lib.rs"]}\npub fn later() -> u8 {\n    7\n}\n`);
    const fixed = await stop(false);
    expect(fixed).toMatchObject({ exitCode: 0, stdout: "", stderr: "" });
    writeFileSync(join(repo.path, "src/lib.rs"), `${CLEAN["src/lib.rs"]}\n${TODO_LINE}`);
    const guarded = await stop(true);
    expect(guarded).toMatchObject({ exitCode: 0, stdout: "", stderr: "" });
  });
});

