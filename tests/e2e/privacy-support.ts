// The planted probe of `tasks/e2e-catalog/failures.md` section PV: a git
// workspace under a HOME that carries a username, beside a CARGO_HOME, a
// target directory and a TMPDIR outside it, holding every credential shape
// the repository pass knows and an environment full of secrets. Every value
// is built at runtime, so no credential-shaped literal is committed.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { CARGO_HOME, runCommand, scratchDir, type Sandbox } from "./e2e-helpers";
import { credential } from "./git-scenario";

export const USER = "SECRETUSER";

// Every planted value, and the private paths, that no output may carry.
export type Probe = {
  workspace: string;
  sandbox: Sandbox;
  target: string;
  env: Record<string, string>;
  // The secrets planted in tracked files.
  planted: Record<string, string>;
  // Values that live only in the environment.
  environment: Record<string, string>;
  // Every string no output may contain.
  needles: string[];
};

const ALNUM = "Q7mR2xK9vL4pW8nB3cZ6hJ1fT5sD0aG8eU2iY4oN";

function tail(length: number, offset = 0): string {
  return Array.from({ length }, (_, index) => ALNUM[(index * 7 + offset) % ALNUM.length]).join("");
}

export function secrets(): Record<string, string> {
  return {
    accessKey: credential("access-key"),
    token: credential("token"),
    apiKey: ["s", "k-"].join("") + "live" + tail(24, 3),
    databaseUrl: credential("database-url"),
    fallback: "fallback" + "secret" + tail(12, 5),
    slack: ["xo", "xb-"].join("") + tail(24, 11),
    workflowToken: ["gh", "p_"].join("") + tail(36, 13),
    pemBody: "MIIEvQ" + tail(58, 17),
  };
}

export function environmentSecrets(): Record<string, string> {
  return {
    SECRET_TOKEN_ENV: "envsecret" + tail(20, 19),
    GITHUB_TOKEN: ["gh", "p_"].join("") + tail(36, 23),
    AWS_SECRET_ACCESS_KEY: "awssecret" + tail(30, 29),
    DATABASE_URL: ["postgres", "://ops:"].join("") + "envpass" + tail(10, 31) + "@db.ops.net/ops",
  };
}

function pem(body: string): string {
  const header = ["-----BEGIN", "PRIVATE KEY-----"].join(" ");
  const footer = ["-----END", "PRIVATE KEY-----"].join(" ");
  return `${header}\n${body}\n${body.split("").reverse().join("")}\n${footer}\n`;
}

// The probe's tracked files. `src/lib.rs` keeps the access key beside an
// `unwrap`, so the frame of that finding prints the key's line too, and
// passes both a credential and plain words through `.to_string()`, so the
// suggestion Clippy offers for the second shows what is withheld for the
// first.
export function probeFiles(planted: Record<string, string>): Record<string, string> {
  return {
    "Cargo.toml": '[package]\nname = "probe"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n\n[workspace]\n',
    "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "probe"\nversion = "0.1.0"\n',
    ".gitignore": "/target\n",
    "src/lib.rs": [
      "pub fn key() -> &'static str {",
      `    "${planted.accessKey}"`,
      "}",
      "pub fn first(value: Option<u8>) -> u8 { value.unwrap() }",
      "",
      "pub fn token() -> &'static str {",
      `    "${planted.token}"`,
      "}",
      "",
      "pub fn api(value: Option<u8>) -> u8 {",
      `    value.expect("${planted.apiKey}")`,
      "}",
      "",
      "pub fn signing() -> String {",
      `    std::env::var("JWT_SECRET").unwrap_or("${planted.fallback}".to_owned())`,
      "}",
      "",
      "fn takes(value: &str) -> usize {",
      "    value.len()",
      "}",
      "",
      "pub fn owned() -> usize {",
      `    takes(&"${planted.slack}".to_string())`,
      "}",
      "",
      "pub fn plain() -> usize {",
      '    takes(&"plain words".to_string())',
      "}",
      "",
    ].join("\n"),
    ".env": "MODE=production\n",
    "config/db.toml": `url = "${planted.databaseUrl}"\n`,
    "keys/server.pem": pem(planted.pemBody!),
    ".github/workflows/ci.yml": `on: push\njobs:\n  deploy:\n    runs-on: ubuntu-latest\n    steps:\n      - run: curl -H "Authorization: token ${planted.workflowToken}" https://api.github.com/user\n`,
  };
}

async function git(cwd: string, box: Sandbox, args: string[]): Promise<void> {
  const identity = { GIT_AUTHOR_NAME: USER, GIT_AUTHOR_EMAIL: `${USER.toLowerCase()}@example.invalid`, GIT_COMMITTER_NAME: USER, GIT_COMMITTER_EMAIL: `${USER.toLowerCase()}@example.invalid` };
  const run = await runCommand(["git", "-c", "init.defaultBranch=main", "-c", "commit.gpgsign=false", "-c", "core.hooksPath=/dev/null", ...args], { cwd, sandbox: box, env: identity });
  if (run.exitCode !== 0) throw new Error(`git ${args.join(" ")} failed: ${run.stderr}`);
}

export async function buildProbe(): Promise<Probe> {
  const root = scratchDir("privacy");
  const home = join(root, `home-${USER}`, `u-${USER}-q7`);
  const tmp = join(root, "tmp");
  const target = join(root, "target");
  const workspace = join(home, "My Projects", "ws ünï-zz");
  mkdirSync(tmp, { recursive: true });
  mkdirSync(workspace, { recursive: true });
  const box: Sandbox = { dir: root, home, tmp };
  const planted = secrets();
  for (const [path, body] of Object.entries(probeFiles(planted))) {
    mkdirSync(dirname(join(workspace, path)), { recursive: true });
    writeFileSync(join(workspace, path), body);
  }
  await git(workspace, box, ["init", "-q"]);
  await git(workspace, box, ["add", "-A"]);
  await git(workspace, box, ["commit", "-q", "-m", "probe"]);
  const environment = environmentSecrets();
  const env = {
    USER,
    LOGNAME: USER,
    ...environment,
    RUSTFLAGS: "-D warnings --cfg planted_rustflag_zz",
  };
  const realHome = process.env.HOME ?? "/home";
  const needles = [
    root, home, workspace, tmp, target, CARGO_HOME, realHome, "/tmp/",
    USER, USER.toLowerCase(), "My Projects", "ünï", "planted_rustflag",
    ...Object.values(planted),
    ...Object.values(environment),
  ];
  return { workspace, sandbox: box, target, env, planted, environment, needles };
}

// The needles `text` carries, each named once.
export function leaks(text: string, needles: string[]): string[] {
  return needles.filter((needle) => text.includes(needle));
}
