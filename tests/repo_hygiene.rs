/// FR-15: all three rules stay switchable off through the same override
/// surface as every other rule.
#[test]
fn the_three_rules_are_switchable_off() {
    let root = workspace("repo-hygiene-switch-off");
    fs::write(root.join(".env"), "EXAMPLE_ONLY=placeholder\n").unwrap();
    let key = fake_aws_key();
    fs::write(
        root.join("src/lib.rs"),
        format!("pub fn fixture() -> &'static str {{\n    \"{key}\"\n}}\n"),
    )
    .unwrap();
    commit_all(&root);

    let mut request = InspectRequest::new(&root);
    for code in [SECRET_FILE, CREDENTIAL, BUILD_OUTPUT] {
        request = request.with_rule_override(RuleOverride::new(code, RuleLevel::Off));
    }
    let report = inspect(request);
    assert_eq!(report.status, Status::Complete, "{:?}", report.errors);
    let report = serde_json::to_value(&report).expect("a valid report should serialize");
    for code in [SECRET_FILE, CREDENTIAL, BUILD_OUTPUT] {
        assert!(
            diagnostics_of(&report, code).is_empty(),
            "{code} still fired switched off"
        );
    }
}

fn rust_doctor(root: &Path, arguments: &[&str]) -> std::process::Output {
    Command::new(env!("CARGO_BIN_EXE_rust-doctor"))
        .args(arguments)
        .env("CARGO_TARGET_DIR", support::scan_target(root))
        .env_remove("RUSTFLAGS")
        .output()
        .expect("the binary should start")
}

/// US-001 and FR-12 on rendered text: the linear report draws a code frame
/// under every finding, and neither it nor the Markdown a CI job posts prints
/// a key the scan matched, on the reported line or on the lines around it.
#[test]
fn a_detected_credential_is_absent_from_every_rendered_surface() {
    let root = workspace("repo-hygiene-rendered");
    fs::write(root.join(".gitignore"), "/target\n").unwrap();
    let key = fake_aws_key();
    let token = format!("xoxb-{}", "1234567890ab");
    fs::write(
        root.join("src/lib.rs"),
        format!(
            "pub fn fixture() -> &'static str {{\n    \"{key}\"\n}}\n\
             pub const OTHER: &str = \"{token}\";\n"
        ),
    )
    .unwrap();
    commit_all(&root);
    let path = root.to_str().unwrap();

    let linear = rust_doctor(&root, &[path, "--yes", "--verbose"]);
    let stdout = String::from_utf8_lossy(&linear.stdout);
    assert!(stdout.contains(CREDENTIAL), "{stdout}");
    assert!(stdout.contains("AKIA<redacted>"), "{stdout}");
    assert!(!stdout.contains(&key) && !stdout.contains(&token), "{stdout}");
    let stderr = String::from_utf8_lossy(&linear.stderr);
    assert!(!stderr.contains(&key) && !stderr.contains(&token), "{stderr}");

    let json = rust_doctor(&root, &[path, "--yes", "--json"]);
    let saved = root.join("target/report.json");
    fs::create_dir_all(root.join("target")).unwrap();
    fs::write(&saved, &json.stdout).unwrap();
    let markdown = rust_doctor(&root, &["report", "markdown", saved.to_str().unwrap()]);
    let rendered = String::from_utf8_lossy(&markdown.stdout);
    assert!(rendered.contains("hardcoded_credential"), "{rendered}");
    assert!(!rendered.contains(&key) && !rendered.contains(&token), "{rendered}");
}

/// Every string of a JSON document, keys included, so an assertion on what a
/// report never says reads all of it.
fn strings_of(value: &Value) -> Vec<String> {
    match value {
        Value::String(text) => vec![text.clone()],
        Value::Array(items) => items.iter().flat_map(strings_of).collect(),
        Value::Object(fields) => fields
            .iter()
            .flat_map(|(key, value)| std::iter::once(key.clone()).chain(strings_of(value)))
            .collect(),
        _ => Vec::new(),
    }
}

/// EP-001 US-001: Clippy's `unnecessary_to_owned` fix for a Slack bot token
/// passed through `.to_string()` is the token itself. It is withheld from the
/// JSON and from the linear report, the finding stays, and the same fix over
/// a literal no pattern matches is published as Clippy wrote it.
#[test]
fn a_suggestion_carrying_a_credential_is_withheld_and_a_plain_one_kept() {
    let root = workspace("repo-hygiene-suggestion");
    fs::write(root.join(".gitignore"), "/target\n").unwrap();
    let body = format!("{}-{}", "1234567890", "abcdefABCDEF");
    fs::write(
        root.join("src/lib.rs"),
        format!(
            "fn takes(value: &str) -> usize {{\n    value.len()\n}}\n\n\
             pub fn send() -> usize {{\n    takes(&\"xoxb-{body}\".to_string())\n}}\n\n\
             pub fn plain() -> usize {{\n    takes(&\"plain words\".to_string())\n}}\n"
        ),
    )
    .unwrap();
    commit_all(&root);
    let path = root.to_str().unwrap();

    let json = rust_doctor(&root, &[path, "--yes", "--json"]);
    let report: Value = serde_json::from_slice(&json.stdout).unwrap();
    let fixes: Vec<&Value> = diagnostics_of(&report, "clippy::unnecessary_to_owned")
        .into_iter()
        .map(|diagnostic| &diagnostic["suggestion"])
        .collect();
    assert_eq!(fixes.len(), 2, "{report:#}");
    assert!(fixes[0].is_null(), "{report:#}");
    assert_eq!(fixes[1]["replacement"], "\"plain words\"");
    assert_eq!(diagnostics_of(&report, CREDENTIAL).len(), 1);
    for text in strings_of(&report) {
        assert!(!text.contains(&body), "{text}");
    }

    let linear = rust_doctor(&root, &[path, "--yes", "--verbose"]);
    let stdout = String::from_utf8_lossy(&linear.stdout);
    let stderr = String::from_utf8_lossy(&linear.stderr);
    assert!(stdout.contains("unnecessary_to_owned"), "{stdout}");
    assert_eq!(stdout.matches("Replace with:").count(), 1, "{stdout}");
    assert!(stdout.contains("Replace with: \"plain words\""), "{stdout}");
    assert!(!stdout.contains(&body) && !stderr.contains(&body), "{stdout}{stderr}");
}

/// EP-001 US-003: the pre-commit hook's scan, `--staged --scope lines`, sees
/// what the commit records. A key staged in a new file and a `.env` forced
/// past the ignore file are both reported, and a working tree that no longer
/// holds the key decides nothing.
#[test]
fn a_staged_key_and_a_force_added_env_are_reported_by_the_staged_scan() {
    let root = workspace("repo-hygiene-staged");
    fs::write(root.join(".gitignore"), "/target\n.env\n").unwrap();
    commit_all(&root);
    fs::write(
        root.join("src/leak.rs"),
        format!("pub const KEY: &str = \"{}\";\n", fake_aws_key()),
    )
    .unwrap();
    fs::write(root.join("src/lib.rs"), "mod leak;\npub fn fixture() -> u32 {\n    2\n}\n").unwrap();
    fs::write(root.join(".env"), "TOKEN=1\n").unwrap();
    git(&root, &["add", "src"]);
    git(&root, &["add", "--force", ".env"]);
    // The working tree no longer holds the key; the index still does.
    fs::write(root.join("src/leak.rs"), "pub const KEY: &str = \"\";\n").unwrap();

    let output = rust_doctor(
        &root,
        &[root.to_str().unwrap(), "--yes", "--json", "--staged", "--scope", "lines"],
    );
    let report: Value = serde_json::from_slice(&output.stdout).unwrap();
    let credential = diagnostics_of(&report, CREDENTIAL);
    assert_eq!(credential.len(), 1, "{report:#}");
    assert_eq!(credential[0]["path"], "src/leak.rs");
    let secret_file = diagnostics_of(&report, SECRET_FILE);
    assert_eq!(secret_file.len(), 1, "{report:#}");
    assert_eq!(secret_file[0]["path"], ".env");
}

/// US-019: a P1 credential finding means a key was committed. A parser's PEM
/// header, AWS's documented key and a template's database URL stay silent; a
/// key body under a header and a deployed database password are reported, and
/// neither value reaches the rendered report.
#[test]
fn only_a_committed_key_or_deployed_password_is_a_credential() {
    let root = workspace("repo-hygiene-credential-shapes");
    fs::write(root.join(".gitignore"), "/target\n").unwrap();
    let header = format!("-----BEGIN {}-----", "PRIVATE KEY");
    let footer = format!("-----END {}-----", "PRIVATE KEY");
    let documented = format!("AKIA{}", "IOSFODNN7EXAMPLE");
    fs::write(
        root.join("src/lib.rs"),
        format!(
            "pub const HEADER: &str = \"{header}\";\n\
             pub const FOOTER: &str = \"{footer}\";\n\
             pub const DOCUMENTED: &str = \"{documented}\";\n\
             pub const LOCAL: &str = \"postgres://user:pass@localhost/db\";\n"
        ),
    )
    .unwrap();
    commit_all(&root);
    assert!(diagnostics_of(&report(&root), CREDENTIAL).is_empty());

    let body = format!("MII{}", "Ev".repeat(30));
    let password = "Xk29fj3lQ";
    fs::write(
        root.join("src/keys.rs"),
        format!(
            "pub const KEY: &str = \"{header}\n\\\n{body}\n\\\n{footer}\";\n\
             pub const URL: &str = \"postgres://app:{password}@db.internal.example.net/prod\";\n"
        ),
    )
    .unwrap();
    fs::write(root.join("src/lib.rs"), "pub mod keys;\n").unwrap();
    commit_all(&root);
    let report = report(&root);
    let mut observed: Vec<(u64, String)> = diagnostics_of(&report, CREDENTIAL)
        .iter()
        .map(|finding| {
            (
                finding["span"]["line_start"].as_u64().unwrap(),
                finding["message"].as_str().unwrap().to_owned(),
            )
        })
        .collect();
    observed.sort();
    assert_eq!(observed.len(), 2, "{report}");
    assert_eq!(observed[0].0, 1);
    assert!(observed[0].1.contains("private key block"), "{observed:?}");
    // The key's literal spans lines 1 to 5, its body on line 3.
    assert_eq!(observed[1].0, 6);
    assert!(observed[1].1.contains("database URL password"), "{observed:?}");

    let path = root.to_str().unwrap();
    let linear = rust_doctor(&root, &[path, "--yes", "--verbose"]);
    let stdout = String::from_utf8_lossy(&linear.stdout);
    assert!(stdout.contains(CREDENTIAL), "{stdout}");
    assert!(!stdout.contains(&body) && !stdout.contains(password), "{stdout}");
}

/// US-043: a binary's lockfile that exists, is untracked and is ignored is
