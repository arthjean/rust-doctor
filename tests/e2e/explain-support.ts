// The `twoMember` workspace of `tasks/e2e-catalog/subcommands.md` section 0,
// shared by the files of `rules`, `why` and `report markdown`: a virtual
// workspace whose root configuration raises `clippy::todo` to error, turns
// correctness off, and overrides both under `b/**` and `a/src/*.rs`.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { scratchDir } from "./e2e-helpers";

export const TWO_MEMBER_CONFIG = [
  "[rules]",
  '"clippy::todo" = "error"',
  "",
  "[categories]",
  'correctness = "off"',
  "",
  "[[overrides]]",
  'paths = ["b/**"]',
  'rules = { "clippy::todo" = "off" }',
  "",
  "[[overrides]]",
  'paths = ["a/src/*.rs"]',
  'categories = { correctness = "error" }',
  "",
].join("\n");

export function twoMemberFiles(): Record<string, string> {
  const member = (name: string) => `[package]\nname = "${name}"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n`;
  return {
    "Cargo.toml": '[workspace]\nmembers = ["a", "b"]\nresolver = "3"\n',
    "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "a"\nversion = "0.1.0"\n\n[[package]]\nname = "b"\nversion = "0.1.0"\n',
    ".gitignore": "/target\n",
    "rust-doctor.toml": TWO_MEMBER_CONFIG,
    "a/Cargo.toml": member("a"),
    "a/src/lib.rs": "pub fn a() -> u8 {\n    todo!()\n}\n",
    "b/Cargo.toml": member("b"),
    "b/src/lib.rs": "pub fn b() -> u8 {\n    todo!()\n}\n",
  };
}

export function writeTree(dir: string, files: Record<string, string | Uint8Array>): string {
  for (const [path, body] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), body);
  }
  return dir;
}

// A fresh copy of `twoMember` outside git, for the commands that compile nothing.
export function twoMember(label = "two-member"): string {
  return writeTree(join(scratchDir(label), "two-member"), twoMemberFiles());
}
