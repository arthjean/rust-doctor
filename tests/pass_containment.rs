#![cfg_attr(test, allow(clippy::unwrap_used, clippy::expect_used))]

//! EP-001 US-002 to US-004: a pass that panics degrades into one
//! `pass-panicked` error at its stage, the other passes' findings stay, the
//! child Clippy started does not outlive the panic, and a panic no pass
//! contained ends the run with one fixed line and exit 2.
//!
//! Every proof runs the debug binary, which panics on request at the site
//! `RUST_DOCTOR_INJECT_PANIC` names, inside a fresh git repository that gives
//! each native producer a finding to lose or keep.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Output;
use std::sync::atomic::AtomicUsize;
use std::time::Duration;

use serde_json::Value;

mod support;

const INJECT: &str = "RUST_DOCTOR_INJECT_PANIC";
/// What every injected payload says, which nothing the run prints may quote.
const PAYLOAD: &str = "injected fault";
const UNUSED: &str = "rust_doctor::cargo::unused_dependency";

static NEXT_WORKSPACE: AtomicUsize = AtomicUsize::new(0);

/// A committed workspace with a finding for every native producer: a release
/// profile keeping debug symbols, an unused path dependency, a tracked `.env`,
/// a shell command built from an argument, a crate-level allow and a file no
/// module declares. `main` replaces `src/main.rs` when given.
fn workspace(main: Option<&str>, build: Option<&str>) -> PathBuf {
    let root = support::fresh_workspace("pass-containment", &NEXT_WORKSPACE);
    let files = [
        (
            "Cargo.toml",
            "[package]\nname = \"containment\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n\
             [dependencies]\nhelper = { path = \"helper\" }\n\n[profile.release]\ndebug = true\n\n[workspace]\n",
        ),
        (
            "Cargo.lock",
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n\
             [[package]]\nname = \"containment\"\nversion = \"0.1.0\"\ndependencies = [\n \"helper\",\n]\n\n\
             [[package]]\nname = \"helper\"\nversion = \"0.1.0\"\n",
        ),
        ("helper/Cargo.toml", "[package]\nname = \"helper\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n"),
        ("helper/src/lib.rs", "pub fn help() {}\n"),
        (".env", "EXAMPLE_ONLY=not-a-real-secret\n"),
        (
            "src/main.rs",
            main.unwrap_or(
                "#![allow(dead_code)]\n\nfn pause(secs: &str) {\n    \
                 let _ = std::process::Command::new(\"sh\").arg(\"-c\").arg(format!(\"sleep {secs}\")).status();\n}\n\n\
                 fn main() {\n    pause(\"0\");\n}\n",
            ),
        ),
        ("src/orphan.rs", "pub fn lost() {}\n"),
    ];
    for (path, contents) in files {
        let path = root.join(path);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, contents).unwrap();
    }
    if let Some(build) = build {
        fs::write(root.join("build.rs"), build).unwrap();
    }
    for arguments in [
        &["init", "--quiet"][..],
        &["add", "-A"],
        &[
            "-c",
            "user.name=Rust Doctor",
            "-c",
            "user.email=rust-doctor@example.invalid",
            "-c",
            "commit.gpgsign=false",
            "commit",
            "--quiet",
            "-m",
            "base",
        ],
    ] {
        let output = support::git_output(&root, arguments);
        assert!(output.status.success(), "git {arguments:?}: {output:?}");
    }
    root
}

/// The binary's JSON run on `root`, Clippy off unless `clippy` is set, with a
/// fault injected at `site` when one is given.
fn scan(root: &Path, site: Option<&str>, clippy: bool) -> Output {
    let mut command = support::rust_doctor();
    command
        .arg(root)
        .args(["--yes", "--json"])
        .args(support::NO_ADVISORY_DB)
        .env("CARGO_TARGET_DIR", support::scan_target(root))
        .env("CARGO_NET_OFFLINE", "true")
        .env_remove("CARGO_ENCODED_RUSTFLAGS")
        .env_remove(INJECT);
    if !clippy {
        for entry in rust_doctor::catalog() {
            if entry.id.starts_with("clippy::") {
                command.arg("--rule").arg(format!("{}=off", entry.id));
            }
        }
    }
    if let Some(site) = site {
        command.env(INJECT, site);
    }
    command.output().unwrap()
}

fn report(output: &Output) -> Value {
    let stderr = String::from_utf8_lossy(&output.stderr);
    let stdout = String::from_utf8_lossy(&output.stdout);
    assert!(!stdout.contains(PAYLOAD), "{stdout}");
    assert!(!stderr.contains(PAYLOAD) && !stderr.contains("panicked"), "{stderr}");
    let report = serde_json::from_slice(&output.stdout);
    assert!(report.is_ok(), "{stderr}");
    report.unwrap()
}

fn codes(report: &Value) -> BTreeSet<String> {
    report["diagnostics"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|diagnostic| diagnostic["code"].as_str().map(str::to_owned))
        .collect()
}

/// A degraded report: incomplete rather than failed, not authoritative, and
/// one `pass-panicked` error at `stage`, the only error it carries.
fn assert_degraded(output: &Output, report: &Value, stage: &str) {
    assert_eq!(report["status"], "incomplete", "{}", report["errors"]);
    assert_eq!(report["complete"], false);
    // A walk that panicked measured no line, so there is no score at all to
    // call authoritative; every other degraded report keeps one that is not.
    let score = &report["audit"]["score"];
    assert!(score.is_null() || score["authoritative"] == false, "{}", report["audit"]);
    let errors = report["errors"].as_array().unwrap();
    assert_eq!(errors.len(), 1, "{errors:?}");
    assert_eq!(errors[0]["stage"], stage);
    assert_eq!(errors[0]["code"], "pass-panicked");
    assert_eq!(
        errors[0]["message"],
        format!("The {stage} pass failed; the score is not authoritative.")
    );
    // An incomplete report exits 1, as a failed producer always made it.
    assert_eq!(output.status.code(), Some(1));
}

#[test]
fn a_panic_in_each_native_pass_drops_that_pass_alone() {
    let root = workspace(None, None);
    let healthy = report(&scan(&root, None, false));
    assert_eq!(healthy["status"], "complete", "{}", healthy["errors"]);
    let all = codes(&healthy);
    let producer = |prefix: &str| -> BTreeSet<String> {
        all.iter().filter(|code| code.starts_with(prefix)).cloned().collect()
    };
    let (cargo, repo, source, structure) = (
        producer("rust_doctor::cargo::"),
        producer("rust_doctor::repo::"),
        producer("rust_doctor::source::"),
        producer("rust_doctor::structure::"),
    );
    for (name, found) in [("cargo", &cargo), ("repo", &repo), ("source", &source), ("structure", &structure)] {
        assert!(!found.is_empty(), "the workspace gives the {name} producer no finding: {all:?}");
    }
    assert!(cargo.contains(UNUSED), "{cargo:?}");
    let truth = BTreeSet::from([UNUSED.to_owned()]);
    let walked: BTreeSet<String> = source.union(&structure).chain(&truth).cloned().collect();

    for (site, stage, lost) in [
        ("cargo_health", "dependencies", &cargo),
        ("repo", "repo", &repo),
        ("walk", "source", &walked),
        ("source_kernel", "source", &source),
        ("dependency_truth", "dependencies", &truth),
        ("structure", "structure", &structure),
    ] {
        let output = scan(&root, Some(site), false);
        let degraded = report(&output);
        assert_degraded(&output, &degraded, stage);
        assert_eq!(degraded["audit"]["score"].is_null(), site == "walk", "{}", degraded["audit"]);
        let kept: BTreeSet<String> = all.difference(lost).cloned().collect();
        assert_eq!(codes(&degraded), kept, "a panic at {site}");
    }
}

#[test]
fn a_panicking_clippy_pass_keeps_the_native_findings() {
    let root = workspace(Some("fn main() {\n    println!(\"hello\");\n}\n"), None);
    let healthy = report(&scan(&root, None, true));
    assert!(codes(&healthy).contains("clippy::print_stdout"), "{}", healthy["diagnostics"]);
    let natives: BTreeSet<String> = codes(&healthy)
        .into_iter()
        .filter(|code| code.starts_with("rust_doctor::"))
        .collect();

    let output = scan(&root, Some("clippy"), true);
    let degraded = report(&output);
    assert_degraded(&output, &degraded, "execution");
    assert_eq!(codes(&degraded), natives);
}

#[test]
fn a_failing_build_script_keeps_the_native_findings() {
    let root = workspace(None, Some("fn main() {\n    std::process::exit(1);\n}\n"));
    let output = scan(&root, None, true);
    let report = report(&output);
    assert_eq!(report["status"], "incomplete", "{}", report["errors"]);
    assert_eq!(report["complete"], false);
    // The errors a failed build always published, as `tests/e2e` pins them,
    // and no containment error: the pass failed, it did not panic.
    let errors: Vec<String> = report["errors"]
        .as_array()
        .unwrap()
        .iter()
        .map(|error| format!("{}/{}", error["stage"].as_str().unwrap(), error["code"].as_str().unwrap()))
        .collect();
    assert_eq!(errors, ["clippy/packages-unlinted", "execution/build-failed", "execution/clippy-exit"]);
    assert_eq!(output.status.code(), Some(1));
    let found = codes(&report);
    for code in [UNUSED, "rust_doctor::repo::tracked_secret_file", "rust_doctor::structure::orphan_module_file"] {
        assert!(found.contains(code), "{code} missing from {found:?}");
    }
}

/// A process the build script leaves sleeping in Cargo's group stands for the
/// `cargo clippy` tree: the panic in the stream reader has to take it down.
#[cfg(unix)]
#[test]
fn a_panic_in_the_clippy_stream_kills_the_child_tree() {
    let pid_file = support::fresh_workspace("pass-containment-pid", &NEXT_WORKSPACE).join("sleeper.pid");
    let build = format!(
        "use std::process::{{Command, Stdio}};\n\nfn main() {{\n    \
         let sleeper = Command::new(\"sleep\").arg(\"120\").stdin(Stdio::null()).stdout(Stdio::null())\n        \
         .stderr(Stdio::null()).spawn().unwrap();\n    \
         std::fs::write({:?}, sleeper.id().to_string()).unwrap();\n}}\n",
        pid_file.to_str().unwrap()
    );
    let root = workspace(None, Some(&build));
    let output = scan(&root, Some("clippy_stream"), true);
    let degraded = report(&output);
    assert_degraded(&output, &degraded, "execution");
    let sleeper = fs::read_to_string(&pid_file).unwrap();
    let pid: u32 = sleeper.trim().parse().unwrap();
    let gone = (0..50).any(|_| {
        let alive = rust_doctor_is_running(pid);
        if alive {
            std::thread::sleep(Duration::from_millis(40));
        }
        !alive
    });
    assert!(gone, "the process {pid} Clippy's build left survived the panic");
}

#[cfg(unix)]
fn rust_doctor_is_running(pid: u32) -> bool {
    std::process::Command::new("kill")
        .args(["-0", &pid.to_string()])
        .stderr(std::process::Stdio::null())
        .status()
        .unwrap()
        .success()
}

#[test]
fn a_panic_after_assembly_exits_2_with_one_line_and_no_document() {
    let root = workspace(None, None);
    let output = scan(&root, Some("render"), false);
    assert_eq!(output.status.code(), Some(2));
    assert!(output.stdout.is_empty(), "{}", String::from_utf8_lossy(&output.stdout));
    assert_eq!(
        String::from_utf8_lossy(&output.stderr),
        "rust-doctor: internal error, please report it\n"
    );
}
