// Git histories declared in a few chained calls. Every commit carries a fixed
// identity and date, so the same declaration yields the same hashes on every
// machine, and git runs with hooks off under the environment of `runDoctor`.
// The steps are recorded and run by `build()`, which first refuses a step the
// history cannot hold yet (staging before any commit) and names it.
import { existsSync, mkdirSync, readdirSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { copyWorkspace, runCommand, sandbox, scratchDir, targetDir, type Sandbox } from "./e2e-helpers";

const GIT_FLAGS = [
  "-c", "init.defaultBranch=main",
  "-c", "commit.gpgsign=false",
  "-c", "tag.gpgsign=false",
  "-c", "core.hooksPath=/dev/null",
  "-c", "protocol.file.allow=always",
  "-c", "advice.detachedHead=false",
];

function identity(date?: string): Record<string, string> {
  return {
    GIT_AUTHOR_NAME: "e2e",
    GIT_AUTHOR_EMAIL: "e2e@example.invalid",
    GIT_COMMITTER_NAME: "e2e",
    GIT_COMMITTER_EMAIL: "e2e@example.invalid",
    ...(date ? { GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date } : {}),
  };
}

// The n-th commit of a history is dated 2026-01-01 plus n days.
function commitDate(index: number): string {
  return new Date(Date.UTC(2026, 0, 1 + index)).toISOString().replace(".000", "");
}

// Credential-shaped values built at runtime: a literal of one under
// `tests/e2e/` would be reported by this repository's own scan.
export type CredentialKind = "access-key" | "token" | "database-url";

export function credential(kind: CredentialKind): string {
  switch (kind) {
    case "access-key":
      return ["AK", "IA"].join("") + "Q3VJ7RNYH2KXW4PZ";
    case "token":
      return ["gh", "p_"].join("") + "R8vT2mQ9xL4kW7nB3cY6zH1jF5dS0aG8eU2i";
    case "database-url":
      return ["postgres", "://app:"].join("") + "Vx7Kq2Lm9Rt4Wz8N" + "@db.prod.net/app";
  }
}

// `mini` of `tasks/e2e-catalog/scopes.md`: one crate holding a pre-existing
// `todo!()` at `src/lib.rs:4` and an access key at `src/creds.rs:2`.
export function miniTemplate(): Record<string, string> {
  return {
    "Cargo.toml": '[package]\nname = "mini"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n\n[workspace]\n',
    "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "mini"\nversion = "0.1.0"\n',
    ".gitignore": "/target\n",
    "src/lib.rs": "pub mod creds;\n\npub fn old_debt() -> u8 {\n    todo!()\n}\n\npub fn untouched() -> u8 {\n    1\n}\n",
    "src/creds.rs": `pub fn key() -> &'static str {\n    "${credential("access-key")}"\n}\n`,
  };
}

// `NEWFN`: a second `todo!()`, at line 12 once appended to the `mini` lib.
export const NEW_FN = "\npub fn new_debt() -> u8 {\n    todo!()\n}\n";

export type FileContent = string | { restoreFrom: string };

export function restoreFrom(rev: string): { restoreFrom: string } {
  return { restoreFrom: rev };
}

export type CloneOptions = { depth?: number; branch?: string; singleBranch?: boolean };

export type Repo = {
  name: string;
  path: string;
  sandbox: Sandbox;
  // The repository this one was cloned from, when the history holds a clone.
  origin?: Repo;
  worktrees: Record<string, string>;
  git(args: string[]): Promise<string>;
  sha(rev?: string): Promise<string>;
  // A named scan target for this repository, kept across runs.
  target(key: string): string;
};

type History = { files: boolean; commits: number; cloned: boolean };

type Step = {
  name: string;
  requires?: "content" | "commit" | "clone";
  adds?: "files" | "commit" | "clone";
  // Returns the repository the history continues in when it changes, as a
  // clone does.
  run(repo: Repo, history: History): Promise<Repo | void>;
};

async function git(dir: string, box: Sandbox, args: string[], date?: string): Promise<string> {
  const run = await runCommand(["git", ...GIT_FLAGS, ...args], { sandbox: box, cwd: dir, env: identity(date) });
  if (run.exitCode !== 0) {
    throw new Error(`git ${args.join(" ")} failed in ${dir} (exit ${run.exitCode}): ${run.stderr.trim()}`);
  }
  return run.stdout;
}

function openRepo(name: string, path: string, box: Sandbox, origin?: Repo): Repo {
  return {
    name,
    path,
    sandbox: box,
    origin,
    worktrees: {},
    git: (args) => git(path, box, args),
    sha: async (rev = "HEAD") => (await git(path, box, ["rev-parse", rev])).trim(),
    target: (key) => targetDir(`${name}-${key}`),
  };
}

async function writeInto(repo: Repo, files: Record<string, FileContent>): Promise<void> {
  for (const [path, content] of Object.entries(files)) {
    const full = join(repo.path, path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, typeof content === "string" ? content : await repo.git(["show", `${content.restoreFrom}:${path}`]));
  }
}

async function commitAll(repo: Repo, history: History, message: string, extra: string[] = []): Promise<void> {
  await git(repo.path, repo.sandbox, ["commit", "-q", "--allow-empty", "-m", message, ...extra], commitDate(history.commits));
  history.commits += 1;
}

export class GitScenario {
  private readonly steps: Step[] = [];

  constructor(private readonly name: string) {}

  private step(step: Step): this {
    this.steps.push(step);
    return this;
  }

  template(template: "mini"): this {
    return this.step({ name: `template(${template})`, adds: "files", run: (repo) => writeInto(repo, miniTemplate()) });
  }

  // `nested` of the catalog: the repository root holds a README and a stray
  // `top.rs`, and the `mini` workspace sits at `dir`.
  nested(dir: string, template: "mini"): this {
    const files: Record<string, string> = { "README.md": "# nested\n", "top.rs": "fn top() {}\n" };
    for (const [path, body] of Object.entries(miniTemplate())) files[join(dir, path)] = body;
    return this.step({ name: `nested(${dir}, ${template})`, adds: "files", run: (repo) => writeInto(repo, files) });
  }

  fixture(fixture: string): this {
    return this.step({
      name: `fixture(${fixture})`,
      adds: "files",
      run: async (repo) => void copyWorkspace(fixture, repo.path),
    });
  }

  write(files: Record<string, FileContent>): this {
    return this.step({ name: "write", adds: "files", run: (repo) => writeInto(repo, files) });
  }

  append(path: string, text: string): this {
    return this.step({
      name: `append(${path})`,
      run: async (repo) => {
        const full = join(repo.path, path);
        if (!existsSync(full)) throw new Error(`append(${path}): no such file`);
        writeFileSync(full, readFileSync(full, "utf8") + text);
      },
    });
  }

  commit(message: string): this {
    return this.step({
      name: `commit(${message})`,
      requires: "content",
      adds: "commit",
      run: async (repo, history) => {
        await repo.git(["add", "-A"]);
        await commitAll(repo, history, message);
      },
    });
  }

  branch(name: string): this {
    return this.step({ name: `branch(${name})`, requires: "commit", run: async (repo) => void (await repo.git(["switch", "-q", "-c", name])) });
  }

  switch(name: string): this {
    return this.step({ name: `switch(${name})`, requires: "commit", run: async (repo) => void (await repo.git(["switch", "-q", name])) });
  }

  // Changes written and added to the index, `remove` paths deleted from both.
  stage(change: { write?: Record<string, FileContent>; remove?: string[] }): this {
    return this.step({
      name: "stage",
      requires: "commit",
      run: async (repo) => {
        const files = change.write ?? {};
        await writeInto(repo, files);
        if (Object.keys(files).length > 0) await repo.git(["add", "-f", "--", ...Object.keys(files)]);
        if (change.remove?.length) await repo.git(["rm", "-q", "--", ...change.remove]);
      },
    });
  }

  // Changes to tracked files left out of the index.
  unstaged(files: Record<string, FileContent>): this {
    return this.step({ name: "unstaged", requires: "commit", run: (repo) => writeInto(repo, files) });
  }

  untracked(files: Record<string, FileContent>): this {
    return this.step({ name: "untracked", run: (repo) => writeInto(repo, files) });
  }

  symlink(path: string, target: string): this {
    return this.step({
      name: `symlink(${path})`,
      adds: "files",
      run: async (repo) => {
        mkdirSync(dirname(join(repo.path, path)), { recursive: true });
        symlinkSync(target, join(repo.path, path));
      },
    });
  }

  submodule(path: string, other: Repo): this {
    return this.step({
      name: `submodule(${path})`,
      adds: "files",
      run: async (repo) => void (await repo.git(["submodule", "add", "-q", other.path, path])),
    });
  }

  // Clones the history built so far and continues on the clone, the way
  // `actions/checkout` hands a workflow its repository.
  clone(options: CloneOptions = {}): this {
    return this.step({
      name: "clone",
      requires: "commit",
      adds: "clone",
      run: async (origin) => {
        const path = join(dirname(origin.path), `${origin.name}-clone`);
        const args = ["clone", "-q", "--no-hardlinks"];
        if (options.depth !== undefined) args.push("--depth", String(options.depth));
        if (options.branch !== undefined) args.push("--branch", options.branch);
        if (options.singleBranch) args.push("--single-branch");
        await git(dirname(origin.path), origin.sandbox, [...args, `file://${origin.path}`, path]);
        return openRepo(`${origin.name}-clone`, path, origin.sandbox, origin);
      },
    });
  }

  setHead(branch: string): this {
    return this.step({
      name: `setHead(${branch})`,
      requires: "clone",
      run: async (repo) => void (await repo.git(["remote", "set-head", "origin", branch])),
    });
  }

  worktree(name: string, branch: string): this {
    return this.step({
      name: `worktree(${name})`,
      requires: "commit",
      run: async (repo) => {
        const path = join(dirname(repo.path), `${repo.name}-${name}`);
        await repo.git(["worktree", "add", "-q", "-b", branch, path]);
        repo.worktrees[name] = path;
      },
    });
  }

  detach(rev = "HEAD"): this {
    return this.step({ name: `detach(${rev})`, requires: "commit", run: async (repo) => void (await repo.git(["switch", "-q", "--detach", rev])) });
  }

  orphan(name: string): this {
    return this.step({ name: `orphan(${name})`, requires: "commit", run: async (repo) => void (await repo.git(["switch", "-q", "--orphan", name])) });
  }

  // From the current commit, `left` and `right` each commit once and then
  // merge each other's first commit, so the two tips have two merge bases.
  crissCross(left = "left", right = "right"): this {
    return this.step({
      name: `crissCross(${left}, ${right})`,
      requires: "commit",
      adds: "commit",
      run: async (repo, history) => {
        for (const side of [left, right]) {
          await repo.git(["switch", "-q", "-c", side, side === left ? "HEAD" : `${left}~1`]);
          writeFileSync(join(repo.path, `${side}.txt`), `${side}\n`);
          await repo.git(["add", "--", `${side}.txt`]);
          await commitAll(repo, history, `${side} 1`);
        }
        const tips = { [left]: await repo.sha(left), [right]: await repo.sha(right) };
        for (const [into, from] of [[left, right], [right, left]] as const) {
          await repo.git(["switch", "-q", into]);
          await git(repo.path, repo.sandbox, ["merge", "--no-ff", "-q", "-m", `merge ${from} into ${into}`, tips[from]!], commitDate(history.commits));
          history.commits += 1;
        }
      },
    });
  }

  // A racily clean index: `path` is staged, then written again with the same
  // bytes, so its modification time is no older than the index's and its
  // stat data no longer proves it unchanged. Git has to read the file again,
  // finds it clean, and a command that refreshes the index rewrites it.
  racyIndex(path: string): this {
    return this.step({
      name: `racyIndex(${path})`,
      requires: "commit",
      run: async (repo) => {
        const full = join(repo.path, path);
        const body = readFileSync(full);
        await repo.git(["add", "--", path]);
        writeFileSync(full, body);
      },
    });
  }

  async build(): Promise<Repo> {
    const planned: History = { files: false, commits: 0, cloned: false };
    for (const step of this.steps) {
      const missing = step.requires === "commit" && planned.commits === 0 ? "a commit"
        : step.requires === "content" && !planned.files && planned.commits === 0 ? "a file to commit"
        : step.requires === "clone" && !planned.cloned ? "a clone"
        : undefined;
      if (missing) throw new Error(`git scenario ${this.name}: ${step.name} needs ${missing} first`);
      if (step.adds === "files") planned.files = true;
      if (step.adds === "commit") planned.commits += 1;
      if (step.adds === "clone") planned.cloned = true;
    }
    const box = sandbox(`git-${this.name}`);
    let repo = openRepo(this.name, join(scratchDir(this.name), this.name), box);
    mkdirSync(repo.path, { recursive: true });
    await repo.git(["init", "-q"]);
    const history: History = { files: false, commits: 0, cloned: false };
    for (const step of this.steps) repo = (await step.run(repo, history)) ?? repo;
    return repo;
  }
}

export function gitScenario(name: string): GitScenario {
  return new GitScenario(name);
}

// Resolves once a scan has materialized its snapshot under `tmp`, the moment a
// signal test can interrupt a baseline or staged run.
export async function waitForSnapshot(tmp: string, timeoutMs = 15_000): Promise<string> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const found = readdirSync(tmp).find((name) => name.startsWith("rust-doctor-baseline-"));
    if (found) return join(tmp, found);
    await Bun.sleep(25);
  }
  throw new Error(`no rust-doctor-baseline-* directory appeared in ${tmp} within ${timeoutMs} ms`);
}
