// `tasks/e2e-catalog/failures.md` sections OW and OC: what reaches stdout and
// stderr when the write fails, and the contracts of both streams when it does
// not. The pipelines run under bash so the reader can close early or the
// stream can point at `/dev/full`.
import { beforeAll, describe, expect, test } from "bun:test";
import { existsSync, mkdirSync, renameSync, symlinkSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import {
  copyWorkspace,
  pathWithout,
  runCommand,
  runDoctor,
  sandbox,
  scratchDir,
  spawnDoctor,
  treeFingerprint,
  type DoctorOptions,
  type DoctorRun,
  type Exit,
} from "./e2e-helpers";
import { credential, gitScenario } from "./git-scenario";

type Score = { value: number; label: string; authoritative: boolean };
type Report = {
  schema_version: number;
  status: string;
  audit: { score: Score | null };
  errors: Array<{ stage: string; code: string }>;
  diagnostics: Array<{ code: string | null; related?: unknown[] }>;
  timings?: Record<string, number>;
};

// A scan of `workspace` that must leave it exactly as it found it.
async function scan(workspace: string, args: string[], options: DoctorOptions = {}): Promise<DoctorRun> {
  const before = treeFingerprint(workspace);
  const run = await runDoctor([workspace, "--yes", ...args], options);
  expect(treeFingerprint(workspace)).toBe(before);
  return run;
}

// `rust-doctor ARGS` inside a bash `script`, which names the binary's argument
// list `"$@"`, with the flags `runDoctor` would add.
async function shell(script: string, workspace: string, args: string[]): Promise<Exit> {
  const box = sandbox("shell");
  const before = treeFingerprint(workspace);
  const run = await runCommand(
    ["bash", "-c", script, "bash", workspace, "--yes", "--advisory-db", "/dev/null", ...args],
    { sandbox: box, env: { CARGO_TARGET_DIR: join(box.dir, "target") } },
  );
  if (existsSync(join(workspace, "Cargo.toml"))) expect(treeFingerprint(workspace)).toBe(before);
  return run;
}

const HEAD_10 = 'rust-doctor "$@" | head -c 10; exit "${PIPESTATUS[0]}"';
const PROGRESS = /^(Running native passes\.\.\.|Compiling dependencies\.\.\.|Linting .+ \(\d+\/\d+\))$/;

function expectOneDocument(stdout: string): Report {
  expect(stdout.endsWith("}\n")).toBe(true);
  expect(stdout.indexOf("\n")).toBe(stdout.length - 1);
  const report = JSON.parse(stdout) as Report;
  expect(report.schema_version).toBe(23);
  return report;
}

function notCargo(): string {
  const dir = scratchDir("not-cargo");
  writeFileSync(join(dir, "README"), "not a crate\n");
  return dir;
}

// A crate of `modules` files of `functions` identical bodies: one
// `duplicate_function_body` diagnostic whose `related` list holds every other
// body, the shape behind the 12.8 MB report of WS-17, scaled to stay fast.
function cloneFarm(modules: number, functions: number): string {
  const workspace = join(scratchDir("clone-farm"), "farm");
  mkdirSync(join(workspace, "src"), { recursive: true });
  writeFileSync(join(workspace, "Cargo.toml"), '[package]\nname = "farm"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n');
  writeFileSync(
    join(workspace, "Cargo.lock"),
    '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "farm"\nversion = "0.1.0"\n',
  );
  const body = (index: number) =>
    `pub fn total_${index}(values: &[u32], limit: u32) -> u32 {\n    let mut total = 0;\n    for value in values {\n`
    + `        if *value > limit {\n            total += *value;\n        } else {\n            total = total.saturating_sub(limit);\n        }\n    }\n`
    + `    let doubled = total.saturating_mul(2);\n    doubled.saturating_add(1)\n}\n`;
  const module = Array.from({ length: functions }, (_, index) => body(index)).join("\n");
  let lib = "";
  for (let index = 0; index < modules; index += 1) {
    lib += `pub mod m${index};\n`;
    writeFileSync(join(workspace, "src", `m${index}.rs`), module);
  }
  writeFileSync(join(workspace, "src/lib.rs"), lib);
  return workspace;
}

// The score line of the linear report, `N / 100 LABEL`.
function humanScore(stdout: string): { value: number; label: string } {
  const line = stdout.match(/ (\d+) \/ 100 (.+)$/m);
  if (!line) throw new Error(`no score line in:\n${stdout}`);
  return { value: Number(line[1]), label: line[2]!.trim() };
}

const FARM = { modules: 240, functions: 50 };
let farm: string;

beforeAll(() => {
  farm = cloneFarm(FARM.modules, FARM.functions);
});

describe("output write failures", () => {
  const pipes: Array<[id: string, fixture: string, args: string[], exit: number]> = [
    ["OW-01", "projects/clean", [], 0],
    ["OW-02", "projects/clippy-warning", ["--blocking", "warning"], 1],
    ["OW-03", "projects/clippy-warning", ["--warning-exit-code", "7"], 7],
  ];
  test.each(pipes)("%s --json read by head -c 10 keeps the scan's exit code", async (_id, fixture, args, exit) => {
    const run = await shell(HEAD_10, copyWorkspace(fixture), ["--json", ...args]);
    expect(run.exitCode).toBe(exit);
    expect(run.stdout).toBe('{"schema_v');
    expect(run.stderr).toBe("");
  });

  test("OW-04 the linear report read by head -c 10 keeps the exit code and only progress on stderr", async () => {
    for (const [fixture, args, exit] of pipes.map(([, ...rest]) => rest)) {
      const run = await shell(HEAD_10, copyWorkspace(fixture), args);
      expect(run.exitCode).toBe(exit);
      expect(run.stdout).toBe("Scope: ful");
      const lines = run.stderr.split("\n").filter(Boolean);
      expect(lines.length).toBeGreaterThan(0);
      for (const line of lines) expect(line).toMatch(PROGRESS);
    }
  });

  test("a report larger than the pipe buffer closed early by head -c 10 ends without a panic", async () => {
    // Past the 64 KiB a pipe holds, the binary is still writing when head
    // exits, so the broken pipe is certain rather than a race.
    const run = await shell(HEAD_10, farm, ["--json"]);
    expect(run.signal).toBeNull();
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toBe('{"schema_v');
    expect(run.stderr).not.toContain("panicked");
    expect(run.stderr).toBe("");
  });

  test("OW-05 a closed stdout loses the report without an error", async () => {
    const run = await shell('exec rust-doctor "$@" >&-', copyWorkspace("projects/clean"), ["--json"]);
    expect(run.exitCode).toBe(0);
    expect(run.stdout).toBe("");
    expect(run.stderr).toBe("");
  });

  const full: Array<[id: string, fixture: string, args: string[], stderr: RegExp]> = [
    ["OW-06", "projects/clean", ["--json"], /^Failed to write report: could not serialize report: No space left on device \(os error 28\)\n$/],
    ["OW-07", "projects/clean", [], /\nFailed to write report: could not write report: No space left on device \(os error 28\)\n$/],
    ["OW-08", "not-cargo", ["--json"], /^Failed to write report: could not (serialize|write) report: No space left on device \(os error 28\)\n$/],
  ];
  test.each(full)("%s with stdout on /dev/full exits 2 naming the write error", async (_id, fixture, args, stderr) => {
    const workspace = fixture === "not-cargo" ? notCargo() : copyWorkspace(fixture);
    const run = await shell('exec rust-doctor "$@" >/dev/full', workspace, args);
    expect(run.exitCode).toBe(2);
    expect(run.stderr).toMatch(stderr);
    expect(run.stderr).not.toContain("panicked");
    const before = run.stderr.slice(0, run.stderr.lastIndexOf("Failed to write report"));
    for (const line of before.split("\n").filter(Boolean)) expect(line).toMatch(PROGRESS);
  });
});

describe("output contracts", () => {
  test("OC-01 every --json run prints one document on one line ending in one newline", async () => {
    const runs: Array<[string, string[]]> = [
      ["projects/clean", []],
      ["projects/clippy-warning", ["--blocking", "warning"]],
      ["projects/compile-error", []],
      ["projects/clean", ["--rule", "clippy::does_not_exist=warn"]],
      ["scan-failures/bad-manifest", []],
    ];
    for (const [fixture, args] of runs) expectOneDocument((await scan(copyWorkspace(fixture), ["--json", ...args])).stdout);
    expectOneDocument((await scan(notCargo(), ["--json"])).stdout);
  });

  test("OC-02 a successful --json run is silent on stderr but for the discovery line", async () => {
    const run = await scan(copyWorkspace("projects/clippy-warning"), ["--json"]);
    expect(run.exitCode).toBe(0);
    expect(run.stderr).toBe("");
    const parent = scratchDir("descend");
    copyWorkspace("projects/clean", join(parent, "inner crate"));
    const descended = await scan(parent, ["--json"]);
    expect(descended.exitCode).toBe(0);
    expect(descended.stderr).toBe("No Cargo workspace at this path: scanning the one in inner crate/.\n");
  });

  test("OC-03 a failure before the scan puts the report on stdout and nothing on stderr", async () => {
    const run = await scan(notCargo(), ["--json"]);
    expect(run.exitCode).toBe(2);
    expect(run.stderr).toBe("");
    expect(expectOneDocument(run.stdout).status).toBe("failed");
  });

  test("OC-04 an argument error under --json prints no document", async () => {
    for (const args of [["--bogus"], ["--max-duration", "0"], ["--base", "HEAD"], ["--rule", "nonsense"]]) {
      const run = await scan(copyWorkspace("projects/clean"), ["--json", ...args]);
      expect(run.exitCode).toBe(2);
      expect(run.stdout).toBe("");
      expect(run.stderr).toStartWith("error: ");
    }
  });

  test("OC-05 two scans of one workspace print the same bytes", async () => {
    const workspace = copyWorkspace("kernel-contract/unimplemented");
    const first = await scan(workspace, ["--json"]);
    const second = await scan(workspace, ["--json"]);
    expect(first.stdout.length).toBeGreaterThan(0);
    expect(second.stdout).toBe(first.stdout);
  });

  test("OC-06 a relative, absolute, moved or symlinked path prints the same bytes", async () => {
    const workspace = copyWorkspace("kernel-contract/unimplemented");
    const absolute = await scan(workspace, ["--json"]);
    const before = treeFingerprint(workspace);
    const relative = await runDoctor([".", "--yes", "--json"], { cwd: workspace });
    expect(treeFingerprint(workspace)).toBe(before);
    const link = join(scratchDir("link"), "through-link");
    symlinkSync(workspace, link);
    const linked = await scan(link, ["--json"]);
    const moved = join(dirname(workspace), `moved-${basename(workspace)}`);
    renameSync(workspace, moved);
    const relocated = await scan(moved, ["--json"]);
    expect(absolute.stdout.length).toBeGreaterThan(0);
    for (const run of [relative, linked, relocated]) expect(run.stdout).toBe(absolute.stdout);
  });

  test("OC-07 --timings publishes the milliseconds of every phase, and only when asked", async () => {
    const workspace = copyWorkspace("projects/clippy-warning");
    const timed = expectOneDocument((await scan(workspace, ["--json", "--timings"])).stdout);
    expect(Object.keys(timed.timings ?? {})).toEqual([
      "probes", "metadata", "lint_list", "clippy_dependencies", "clippy_linting",
      "walk", "source_kernel", "structure", "cargo_health", "repo", "total",
    ]);
    for (const value of Object.values(timed.timings!)) expect(Number.isInteger(value) && value >= 0).toBe(true);
    const plain = expectOneDocument((await scan(workspace, ["--json"])).stdout);
    expect("timings" in plain).toBe(false);
  });

  test("OC-08 --verbose changes nothing in a --json report", async () => {
    const workspace = copyWorkspace("kernel-contract/unimplemented");
    const plain = await scan(workspace, ["--json"]);
    const verbose = await scan(workspace, ["--json", "--verbose"]);
    expect(plain.stdout.length).toBeGreaterThan(0);
    expect(verbose.stdout).toBe(plain.stdout);
  });

  test("OC-09 --verbose adds the phase line and every location to the linear report", async () => {
    const workspace = copyWorkspace("kernel-contract/unimplemented");
    const verbose = await scan(workspace, ["--verbose"]);
    const plain = await scan(workspace, []);
    const flat = verbose.stdout.replace(/\n/g, " ");
    expect(flat).toMatch(
      /Phases: probes \d+ ms, metadata \d+ ms, lint list \d+ ms, clippy dependencies \d+ ms, clippy linting \d+ ms, walk \d+ ms, source kernel \d+ ms, structure \d+ ms, cargo health \d+ ms, repo \d+ ms; total \d+ ms/,
    );
    for (const location of ["src/lib.rs:4:5", "src/lib.rs:8:5", "src/lib.rs:12:5"]) expect(verbose.stdout).toContain(location);
    expect(plain.stdout).not.toContain("Phases:");
  });

  test("OC-10 the complete linear report keeps its section order", async () => {
    const run = await scan(copyWorkspace("projects/clippy-warning"), []);
    const sections = [
      "Scope: full codebase\n", "Scored 1 production files", "Top warning: Unwrap used", "Rule ID: clippy::unwrap_used",
      "All 1 occurrences across 1 findings", "Bugs: 0 errors, 1 warnings", "Configuration: none loaded",
      "No local RustSec database", "Gate passed: blocking error", " 100 / 100 Great", "is left out",
      "Share: https://rust-doctor.com/share?", "Docs: https://rust-doctor.com/docs", "GitHub: https://github.com/",
    ];
    const positions = sections.map((section) => run.stdout.indexOf(section));
    for (const [index, section] of sections.entries()) {
      expect({ section, found: positions[index]! >= 0 }).toEqual({ section, found: true });
    }
    expect(positions).toEqual([...positions].sort((left, right) => left - right));
    const incomplete = await scan(copyWorkspace("scan-failures/sleeping-build"), ["--max-duration", "2"]);
    const gate = incomplete.stdout.indexOf("Gate not evaluated");
    const error = incomplete.stdout.indexOf("Scan incomplete: The scan stopped at the 2 s limit");
    const score = incomplete.stdout.indexOf(" / 100 ");
    expect(gate).toBeGreaterThan(0);
    expect(error).toBeGreaterThan(gate);
    expect(score).toBeGreaterThan(error);
  });

  test("OC-11 a failed linear report is the scope line and the failure, without a score", async () => {
    const run = await scan(notCargo(), []);
    expect(run.exitCode).toBe(2);
    expect(run.stdout.replace(/\n(?!$)/g, " ")).toBe(
      "Scope: full codebase Scan failed: no Cargo.toml found in this path or its ancestors (discovery/no-manifest)\n",
    );
    expect(run.stdout).not.toContain("/ 100");
  });

  const scores: Array<[string, string[]]> = [
    ["projects/clean", []],
    ["kernel-contract/todo", []],
    ["kernel-contract/unimplemented", []],
    ["score-credibility/adversarial", []],
    ["projects/clean", ["--package", "clean"]],
    ["scan-failures/sleeping-build", ["--max-duration", "2"]],
  ];
  test("OC-12 the human score equals the JSON score, and only an authoritative one is shared", async () => {
    const seen: number[] = [];
    for (const [fixture, args] of scores) {
      const workspace = copyWorkspace(fixture);
      const score = expectOneDocument((await scan(workspace, ["--json", ...args])).stdout).audit.score!;
      const human = await scan(workspace, args);
      const shown = humanScore(human.stdout);
      seen.push(score.value);
      expect({ fixture, value: shown.value }).toEqual({ fixture, value: score.value });
      if (score.authoritative) {
        expect(shown.label).toBe(score.label);
        expect(human.stdout).toContain(`Share: https://rust-doctor.com/share?s=${score.value}&`);
      } else {
        expect(shown.label).toBe("Core partial");
        expect(human.stdout).not.toContain("Share:");
      }
    }
    expect(new Set(seen).size).toBeGreaterThanOrEqual(4);
  });

  test("OC-13 report markdown republishes neither a masked credential nor a suggestion", async () => {
    const token = credential("token");
    const repo = await gitScenario("oc13")
      .write({
        "Cargo.toml": '[package]\nname = "leak"\nversion = "0.1.0"\nedition = "2024"\npublish = false\n',
        "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "leak"\nversion = "0.1.0"\n',
        ".gitignore": "/target\n",
        "src/lib.rs": `fn takes(value: &str) -> usize {\n    value.len()\n}\n\npub fn owned() -> usize {\n    takes(&"${token}".to_string())\n}\n`,
      })
      .commit("base")
      .build();
    const run = await scan(repo.path, ["--json"], { sandbox: repo.sandbox });
    const report = expectOneDocument(run.stdout);
    expect(report.diagnostics.map((diagnostic) => diagnostic.code)).toEqual(
      expect.arrayContaining(["clippy::unnecessary_to_owned", "rust_doctor::repo::hardcoded_credential"]),
    );
    const saved = join(repo.sandbox.dir, "report.json");
    writeFileSync(saved, run.stdout);
    const markdown = await runDoctor(["report", "markdown", saved], { sandbox: repo.sandbox });
    expect(markdown.exitCode).toBe(0);
    expect(markdown.stdout).toContain("clippy::unnecessary_to_owned");
    for (const output of [run.stdout, markdown.stdout]) {
      expect(output).not.toContain(token);
      expect(output).not.toContain(token.slice(4));
    }
    expect(markdown.stdout).not.toContain("Replace with");
  });

  test("OC-14 a report past a megabyte is still one line ending in one newline", async () => {
    const run = await scan(farm, ["--json"], { timeoutMs: 120_000 });
    expect(run.exitCode).toBe(0);
    expect(run.stdout.length).toBeGreaterThan(1_000_000);
    const report = expectOneDocument(run.stdout);
    const family = report.diagnostics.find((diagnostic) => diagnostic.code === "rust_doctor::structure::duplicate_function_body");
    expect(family?.related?.length).toBe(FARM.modules * FARM.functions - 1);
  }, 150_000);

  test("OC-15 every failed report carries a null score, an interrupted one included", async () => {
    const failed: DoctorRun[] = [
      await scan(notCargo(), ["--json"]),
      await scan(copyWorkspace("projects/clean"), ["--json", "--rule", "clippy::does_not_exist=warn"]),
      await scan(copyWorkspace("projects/clean"), ["--json"], { env: { PATH: pathWithout("rustc") } }),
      await scan(copyWorkspace("scan-failures/bad-manifest"), ["--json"]),
    ];
    const workspace = copyWorkspace("scan-failures/sleeping-build");
    const box = sandbox("interrupt");
    const pidFile = join(box.dir, "sleeper.pid");
    const before = treeFingerprint(workspace);
    const spawned = spawnDoctor([workspace, "--yes", "--json"], { sandbox: box, env: { RUST_DOCTOR_SLEEPER_PID: pidFile } });
    const deadline = Date.now() + 30_000;
    while (!existsSync(pidFile) && Date.now() < deadline) await Bun.sleep(25);
    expect(existsSync(pidFile)).toBe(true);
    spawned.proc.kill("SIGINT");
    failed.push(await spawned.result);
    expect(treeFingerprint(workspace)).toBe(before);
    const stages = failed.map((run) => {
      const report = expectOneDocument(run.stdout);
      expect(report.status).toBe("failed");
      expect(report.audit.score).toBeNull();
      return report.errors[0]!.stage;
    });
    expect(stages).toEqual(["discovery", "policy", "execution", "metadata", "clippy"]);
    expect(failed.at(-1)!.exitCode).toBe(130);
  });
});
