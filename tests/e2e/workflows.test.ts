    expect(row).toBeDefined();
    expect(row).toContain("clippy::todo");
    expect(row).toContain("| error |");
    expect(markdown.stdout).not.toContain("b/src/lib.rs");
    const live = await runDoctor(["why", "a/src/lib.rs:2"], { cwd: workspace });
    expect(live.exitCode).toBe(0);
    expect(live.stdout).toContain("clippy::todo (error)");
