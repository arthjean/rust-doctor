const clean = (name: string, extra: Record<string, string> = {}) =>
  gitScenario(name).write({ ...CLEAN, ...extra }).commit("base").build();

// `clean` with a `.claude/` directory, after a `setup` that found claude
// there and wrote its skill, the pre-commit hook and the Stop hook.
async function setUp(name: string, extra: Record<string, string> = {}): Promise<Repo> {
  const repo = await clean(name, extra);
  mkdirSync(join(repo.path, ".claude"));
  const setup = await runDoctor(["setup", repo.path], { sandbox: repo.sandbox });
  expect(setup.exitCode).toBe(0);
  expect(existsSync(join(repo.path, ".git/hooks/pre-commit"))).toBe(true);
  return repo;
}

// Every git call a test makes itself, hooks on, under the suite's sealed
// environment. The hook's scan builds into the repository's own target.
function git(repo: Repo, args: string[], env: EnvOverrides = {}): Promise<Exit> {
  return runCommand(["git", ...args], {
    sandbox: repo.sandbox,
    cwd: repo.path,
    env: { ...IDENTITY, CARGO_TARGET_DIR: join(repo.sandbox.dir, "hook-target"), ...env },
  });
}

async function stage(repo: Repo, files: Record<string, string>): Promise<void> {
  for (const [path, body] of Object.entries(files)) {
    mkdirSync(join(repo.path, path, ".."), { recursive: true });
    writeFileSync(join(repo.path, path), body);
  }
  expect((await git(repo, ["add", "--", ...Object.keys(files)])).exitCode).toBe(0);
}

const commit = (repo: Repo, message: string, extra: string[] = [], env: EnvOverrides = {}) =>
  git(repo, ["commit", "-q", "-m", message, ...extra], env);

const head = async (repo: Repo) => (await git(repo, ["rev-parse", "HEAD"])).stdout.trim();

type Step = { name?: string; uses?: string; run?: string; env?: Record<string, string> };
type Workflow = { jobs: Record<string, { steps: Step[] }> };

function workflow(repo: Repo): Workflow {
  return Bun.YAML.parse(readFileSync(join(repo.path, ".github/workflows/rust-doctor.yml"), "utf8")) as Workflow;
}

function step(flow: Workflow, name: string): Step {
  const found = Object.values(flow.jobs).flatMap((job) => job.steps).find((entry) => entry.name === name);
  if (!found?.run) throw new Error(`no run step named ${name}`);
  return found;
}

// Replays one `run:` block the way the runner does: bash, in the checkout.
// The inspect step resolves the launcher through `npm prefix -g`, whose stub
// answers a prefix holding the binary under test.
function runStep(repo: Repo, flow: Workflow, name: string, env: EnvOverrides): Promise<Exit> {
  return runCommand(["bash", "-c", step(flow, name).run!], {
    sandbox: repo.sandbox,
    cwd: repo.path,
    env: { CARGO_TARGET_DIR: join(repo.sandbox.dir, "ci-target"), PATH: `${actionTools()}:${toolchainBin()}`, ...env },
  });
}

// `ci install` committed on `main` with an `origin/main` ref, then a branch
// `feature` that adds one `todo!()`: what a pull request's checkout holds.
async function pullRequest(name: string, flags: string[]): Promise<{ repo: Repo; flow: Workflow; runner: string }> {
  const repo = await clean(name);
  expect((await runDoctor(["ci", "install", ...flags, repo.path], { sandbox: repo.sandbox })).exitCode).toBe(0);
  expect((await git(repo, ["add", "-A"])).exitCode).toBe(0);
  expect((await commit(repo, "ci")).exitCode).toBe(0);
  expect((await git(repo, ["update-ref", "refs/remotes/origin/main", "HEAD"])).exitCode).toBe(0);
  expect((await git(repo, ["switch", "-q", "-c", "feature"])).exitCode).toBe(0);
  await stage(repo, { "src/lib.rs": `${CLEAN["src/lib.rs"]}\n${TODO_LINE}` });
  expect((await commit(repo, "feature")).exitCode).toBe(0);
  const runner = scratchDir(`${name}-runner`);
  return { repo, flow: workflow(repo), runner };
}

const JQ = Bun.which("jq", { PATH: "/usr/local/bin:/usr/bin:/bin" });

// A `gh` that logs its first four arguments, one call a line, and the whole
// call beside them, and answers the comment listing from a file,
// with the machine's `jq` beside it: the comment step's two programs.
function ghPath(box: string): { path: string; log: string; comments: string } {
  const bin = join(box, "gh-bin");
  mkdirSync(bin);
  const gh = join(bin, "gh");
  writeFileSync(
    gh,
    '#!/bin/sh\nprintf \'%s %s %s %s\\n\' "$1" "$2" "$3" "$4" >> "$GH_LOG"\nprintf \'%s\\n\' "$*" >> "$GH_LOG.full"\n' +
      'case "$*" in *--paginate*) cat "$GH_COMMENTS" ;; esac\n',
  );
  chmodSync(gh, 0o755);
  if (JQ) symlinkSync(JQ, join(bin, "jq"));
  return { path: `${bin}:${toolchainBin()}`, log: join(box, "gh.log"), comments: join(box, "comments.json") };
}

